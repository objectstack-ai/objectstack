export function render(model, declaredVerdict) {
  const lines = [];
  const rel = (file) => (file ? path.relative(model.root, file) : 'a route entry');
  lines.push('The /docs/[[...slug]] eager closure, as declared:');
  for (const entry of declaredVerdict.recorded) {
    lines.push(`  RECORDED  ${entry.spec}`);
  }
  for (const entry of declaredVerdict.free) {
    lines.push(`  FREE      ${entry.spec}  <- already imported by ${rel(entry.via)}`);
  }
  for (const entry of declaredVerdict.newGraph) {
    lines.push(`  NEW GRAPH ${entry.spec}  (line ${entry.line})`);
  }
  return lines.join('\n');
}

export function main(argv = process.argv.slice(2), env = process.env) {
  const rootFlag = argv.indexOf('--root');
  const root = rootFlag === -1 ? REPO_ROOT : path.resolve(argv[rootFlag + 1]);
  const model = analyse({ root });

  const declared = evaluateDeclared(model);
  const ledger = evaluateLedger(model);
  const gauge = evaluateGauge(model);

  for (const verdict of [declared, ledger]) {
    if (verdict.status === 'pass') console.log(`✅ ${verdict.message}`);
    else console.error(`❌ ${verdict.message}`);
  }
  // The gauge is printed even when it passes, and never silently: a half that
  // says nothing is indistinguishable from a half that was switched off.
  if (gauge.status === 'pass') console.log(`✅ ${gauge.message}`);
  else console.error(`❌ ${gauge.message}`);

  console.log('');
  console.log(render(model, declared));

  if (env?.GITHUB_STEP_SUMMARY) {
    try {
      fs.appendFileSync(
        env.GITHUB_STEP_SUMMARY,
        `### Docs route eager closure\n\n\`\`\`\n${render(model, declared)}\n\`\`\`\n`,
      );
    } catch {
      // A summary that cannot be written is not a verdict about the route.
    }
  }

  if (gauge.status === 'error') return 2;
  return declared.status === 'fail' || ledger.status === 'fail' ? 1 : 0;
}

if (isEntrypoint(import.meta.url)) {
  process.exit(main());
}
