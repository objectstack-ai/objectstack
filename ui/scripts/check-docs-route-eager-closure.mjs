#!/usr/bin/env node
/**
 * The docs route's eager closure, weighed STRUCTURALLY — no build, no bytes.
 *
 * ## The hole this fills (objectui#6316)
 *
 * `apps/site/app/components/registerCatalogBlocks.ts` is a list of side-effect
 * imports. Every one of them pulls its package's module graph into the Next
 * docs route `/docs/[[...slug]]`, which is shared by every docs page — so an
 * import added there is paid on every page of the docs collection
 * `apps/site/source.config.ts` declares, not on the gallery alone. How many that
 * is, is derived: this gate's own `gauge:` line reports it on every run. The cards
 * that added to that list (objectui#4600, objectui#4616, objectui#6167,
 * objectui#6025) all said the cost was governed by `check:eager-closure`.
 *
 * It was not, and this is the measurement that says so, re-taken on `b116a0684`
 * rather than inherited from the card:
 *
 *   - `scripts/check-eager-closure-budget.mjs` reads
 *     `apps/console/dist/eager-closure.json` (`DEFAULT_REPORT_PATH`, line 314 on
 *     that commit — the card quoted line 292, which PR #6315 moved). That report
 *     is written by `emitEagerClosureReport` in `apps/console/vite.config.ts`,
 *     from rolldown's `chunk.imports`, for THE CONSOLE.
 *   - `.github/workflows/performance-budget.yml` triggers on `packages/**`,
 *     `apps/console/**` and `pnpm-lock.yaml`, and builds `@object-ui/console`.
 *
 * `apps/site` is weighed by neither. The only measurement of the docs route
 * that has ever existed is the one in `registerCatalogBlocks.ts`'s own header
 * (`7738.7 kB / 29 chunks` -> `9542.6 kB / 40 chunks`), reconstructed BY HAND
 * from the `script src` set of the prerendered route because Next 16.3 +
 * Turbopack prints no Size / First Load JS columns. It was taken once. Nothing
 * re-takes it, and objectui#4616's `+50%` stop condition has no gauge behind it.
 *
 * ## What this gate asserts, and what it deliberately does not
 *
 * It does NOT weigh bytes. Ruled on objectui#6316: a second byte budget would
 * cost a full docs build in CI — every page of that collection, on every run —
 * and the cheap structural question catches the change that matters anyway. ⛔ No
 * page count in this header, deliberately: the two that used to be here were
 * literals nothing derived, and both were false by the time anyone read them
 * (objectui#9004). Every package named in the registrar is
 * classified into exactly one of three buckets:
 *
 *   RECORDED  it is in {@link MEASURED_PAYLOAD} — its eager cost was argued for
 *             and written down when it landed.
 *   FREE      it is already reachable from the route's module graph without the
 *             registrar naming it, so the import adds a DECLARATION and no
 *             payload. This is the objectui#6314 case, and this gate is what
 *             turns that claim from prose into a measurement: `plugin-form` and
 *             `plugin-grid` are reachable through `@object-ui/plugin-view`'s
 *             module-scope `import { ObjectForm }` / `import { ObjectGrid }`
 *             in `packages/plugin-view/src/ObjectView.tsx`.
 *   NEW GRAPH neither — the import pulls a graph this route has never carried.
 *             That is the change nobody can currently measure, so this gate
 *             fails and a human argues for it in review.
 *
 * The third bucket is the whole point. It converts "an unmeasured hazard" into
 * "a review event", which is all a cheap instrument can honestly do.
 *
 * ## Why {@link MEASURED_PAYLOAD} is a ledger and not a ceiling
 *
 * The eleven packages in it are NOT reachable any other way — measured, and
 * re-measured on every run by {@link evaluateLedger}. They are the payload
 * objectui#4600 and objectui#4616 measured and argued for. Without the ledger
 * this gate would have to be red at rest, and a gate that is red at rest is a
 * gate someone deletes. With it, the assertion is exact: today's list is
 * accounted for, and tomorrow's addition is either free or argued.
 *
 * It carries no bytes and no threshold, so it is not the "second ceiling
 * constant" objectui#6316's ruling closed. Adding an entry is a claim about a
 * graph, in a diff a reviewer reads.
 *
 * ## Source, not dist — and what that approximation costs
 *
 * The traversal reads `src/` and resolves workspace packages to their source
 * entry, so the gate needs no `pnpm install` and no build: a checkout plus one
 * `node` call. `dist/` is generated from `src/` by vite, and rollup preserves
 * static imports it cannot prove dead, so source-level reachability is a
 * SUPERSET of the built closure: this gate can call a package reachable that
 * tree-shaking would have dropped. That direction is the safe one — it can
 * fail to flag a new graph, never invent one — and side-effect imports, which
 * is what every line in the registrar is, are never shaken out at all.
 *
 * ## The MDX half is not optional
 *
 * `apps/site/.source/server.ts` — generated by `fumadocs-mdx`, gitignored — is
 * a static `import` of every `content/docs/**\/*.mdx` file, and `lib/source.ts`
 * pulls it into the route. So the compiled MDX modules ARE in this route's
 * eager graph, and this gate walks `content/docs` directly rather than the
 * generated file, so that it stays a checkout-only gate.
 *
 * That is load-bearing rather than thorough: measured on `b116a0684`, the
 * registrar is reachable from the route entries ONLY through MDX —
 * `content/docs/guide/schema-catalog.mdx` imports `SchemaCatalogIndex`, which
 * imports `SchemaThumbnail`, which imports the registrar. Drop the MDX half and
 * this gate judges a file the route it names does not load. {@link evaluateGauge}
 * asserts that reachability on every run for exactly that reason.
 *
 * Fenced code blocks in MDX are masked before the scan. Not cosmetic: 87 files
 * under `content/docs` open a line with `import`, and the ones naming
 * `@object-ui/plugin-grid`, `@object-ui/plugin-view` and `@object-ui/plugin-calendar`
 * are all inside ``` fences — documentation OF an import, not an import. Count
 * them and `plugin-grid` reads FREE for a reason that does not exist.
 *
 * ## Exit codes
 *
 *   0  every declared package is accounted for and the ledger is honest.
 *   1  a real verdict about the registrar: a new graph, or a stale ledger.
 *   2  the GAUGE is broken — a specifier this gate must resolve did not, the
 *      registrar is no longer on the route, or the traversal stopped
 *      discriminating. Never reported as a size verdict, and never green: a
 *      structural gate that cannot fail is worse than no gate, because it turns
 *      an unmeasured hazard into a false assurance.
 *
 * All three halves are evaluated and printed before any of them decides the
 * code, the way `check-eager-closure-budget.mjs` prints its four.
 */

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { maskComments } from './js-comment-mask.mjs';
import { isEntrypoint } from './invoked-as.mjs';

export const REPO_ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');

/** The file this gate judges, relative to the repo root. */
export const REGISTRAR = 'apps/site/app/components/registerCatalogBlocks.ts';

/**
 * The `/docs/[[...slug]]` route's own entry modules. `app/layout.tsx` is the
 * root layout every route renders inside, `mdx-components.tsx` is what the page
 * hands each compiled MDX module.
 */
export const ROUTE_ENTRIES = Object.freeze([
  'apps/site/app/layout.tsx',
  'apps/site/app/docs/layout.tsx',
  'apps/site/app/docs/[[...slug]]/page.tsx',
  'apps/site/mdx-components.tsx',
]);

/** Where the MDX modules the route compiles live. */
export const MDX_CONTENT_DIR = 'content/docs';

/** The alias `apps/site/tsconfig.json` declares as `"@/*": ["./*"]`. */
export const SITE_DIR = 'apps/site';

/**
 * Packages whose eager cost on this route is ALREADY ARGUED FOR AND RECORDED.
 *
 * Every entry is a package the docs route pulls in ONLY because the registrar
 * names it — checked on every run by {@link evaluateLedger}, which fails if an
 * entry has become reachable some other way (the ledger would then overstate) or
 * has stopped being named at all (a dead entry that would silently pardon a
 * re-added import).
 *
 * SHRINK-ONLY in spirit: adding an entry is the review event this gate exists to
 * create. Say what the package is for and what it cost, the way these do.
 */
export const MEASURED_PAYLOAD = Object.freeze({
  '@object-ui/plugin-dashboard':
    'objectui#4600 — the dashboard category the gallery could not render at all; one of the two the route was first measured with.',
  '@object-ui/plugin-charts':
    'objectui#4600 — `chart` and its variants, the second of that card’s original two.',
  '@object-ui/plugin-calendar':
    'objectui#4616 census — 2 `calendar-view` entries painted OBJUI-001 without it.',
  '@object-ui/plugin-chatbot': 'objectui#4616 census — 3 `chatbot` entries.',
  '@object-ui/plugin-editor': 'objectui#4616 census — 3 `code-editor` entries.',
  '@object-ui/plugin-gantt': 'objectui#4616 census — 3 `object-gantt` entries.',
  '@object-ui/plugin-kanban': 'objectui#4616 census — 2 `kanban` entries.',
  '@object-ui/plugin-map': 'objectui#4616 census — 3 `object-map` entries.',
  '@object-ui/plugin-markdown': 'objectui#4616 census — 3 `markdown` entries.',
  '@object-ui/plugin-timeline': 'objectui#4616 census — 3 `timeline` entries.',
  '@object-ui/plugin-view':
    'objectui#4616 census — filter-ui, sort-ui and view-switcher entries. It is also the package the two FREE declarations below reach their code through.',
});

/**
 * Extensions this gate parses. Anything else resolves but is a leaf — a `.css`
 * or `.json` import is an edge with no further edges of its own.
 *
 * `.mdx` is here and not in {@link TRY_EXTS}: an MDX file is never the TARGET of
 * a specifier in this tree (the generated `.source/server.ts` is), but it is a
 * seed whose own imports are most of the route. Leaving it out is not a smaller
 * graph, it is a different one — the registrar drops off the route entirely,
 * which is exactly what half 3 caught while this file was being written.
 */
const PARSED = new Set(['.ts', '.tsx', '.mts', '.cts', '.js', '.jsx', '.mjs', '.cjs', '.mdx']);
const TRY_EXTS = ['.ts', '.tsx', '.mts', '.cts', '.js', '.jsx', '.mjs', '.cjs'];

// ---------------------------------------------------------------------------
// Reading the workspace
// ---------------------------------------------------------------------------

/**
 * Every workspace package, name -> absolute directory, from the globs
 * `pnpm-workspace.yaml` actually declares. Reading the file rather than
 * hard-coding `packages/`, `apps/`, `examples/` keeps one declaration of what
 * the workspace is; an unsupported glob shape throws instead of being skipped,
 * because a silently narrower workspace makes every package in it read as
 * external — which is to say, as unreachable.
 */
export function readWorkspacePackages(root = REPO_ROOT) {
  const yaml = fs.readFileSync(path.join(root, 'pnpm-workspace.yaml'), 'utf8');
  const block = yaml.slice(yaml.indexOf('packages:'));
  const globs = [];
  for (const line of block.split('\n').slice(1)) {
    if (/^\S/.test(line)) break;
    const m = /^\s*-\s*'?"?([^'"\s]+)'?"?\s*$/.exec(line);
    if (m) globs.push(m[1]);
  }
  if (!globs.length) throw new Error('pnpm-workspace.yaml declared no package globs');

  const dirs = [];
  for (const glob of globs) {
    if (glob.endsWith('/*')) {
      const parent = path.join(root, glob.slice(0, -2));
      if (!fs.existsSync(parent)) continue;
      for (const entry of fs.readdirSync(parent, { withFileTypes: true })) {
        if (entry.isDirectory()) dirs.push(path.join(parent, entry.name));
      }
    } else if (!glob.includes('*')) {
      dirs.push(path.join(root, glob));
    } else {
      throw new Error(`unsupported workspace glob: ${glob}`);
    }
  }

  const byName = new Map();
  for (const dir of dirs) {
    const manifest = path.join(dir, 'package.json');
    if (!fs.existsSync(manifest)) continue;
    const name = JSON.parse(fs.readFileSync(manifest, 'utf8')).name;
    if (name) byName.set(name, dir);
  }
  return byName;
}

// ---------------------------------------------------------------------------
// Resolution
// ---------------------------------------------------------------------------

function resolveFile(candidate) {
  // `moduleResolution: bundler` sources in this tree write `./foo.js` for
  // `./foo.ts`. Resolving the literal path first and only then rewriting the
  // extension would answer with a stale build artefact if one were ever
  // committed; source wins.
  if (/\.(js|jsx|mjs|cjs)$/.test(candidate)) {
    const stem = candidate.replace(/\.(js|jsx|mjs|cjs)$/, '');
    for (const ext of ['.ts', '.tsx', '.mts', '.cts']) {
      if (fs.existsSync(stem + ext)) return stem + ext;
    }
  }
  if (fs.existsSync(candidate) && fs.statSync(candidate).isFile()) return candidate;
  for (const ext of TRY_EXTS) if (fs.existsSync(candidate + ext)) return candidate + ext;
  for (const ext of TRY_EXTS) {
    const index = path.join(candidate, `index${ext}`);
    if (fs.existsSync(index)) return index;
  }
  return null;
}

/** The `src/` file behind a package `exports` target such as `./dist/index.js`. */
function sourceBehind(pkgDir, target) {
  const rel = target.replace(/^\.\//, '').replace(/^dist\//, '');
  return resolveFile(path.join(pkgDir, 'src', rel));
}

/**
 * A workspace package's source entry for `subpath` (undefined = the `.` entry).
 * Returns `{ kind: 'file' | 'unresolved' }`; never a silent null, because a
 * package entry that cannot be found is precisely the shape that would make
 * everything downstream of it read as unreachable.
 */
export function packageEntry(pkgDir, subpath) {
  const manifest = JSON.parse(fs.readFileSync(path.join(pkgDir, 'package.json'), 'utf8'));
  const key = subpath ? `./${subpath}` : '.';
  const declared = manifest.exports?.[key];
  let target = null;
  if (typeof declared === 'string') target = declared;
  else if (declared && typeof declared === 'object') {
    target = declared.import?.default ?? declared.import ?? declared.default ?? declared.require ?? null;
  }
  if (typeof target !== 'string' && !subpath) target = manifest.module ?? manifest.main ?? null;
  if (typeof target !== 'string') {
    return { kind: 'unresolved', why: `no exports["${key}"] in ${manifest.name}` };
  }
  const file = sourceBehind(pkgDir, target);
  return file
    ? { kind: 'file', file }
    : { kind: 'unresolved', why: `no source behind ${manifest.name} -> ${target}` };
}

/**
 * A resolver over one tree. External (non-workspace) specifiers are LEAVES, not
 * failures: `react`, `next/navigation` and the virtual
 * `fumadocs-mdx:collections/server` are all real edges out of this repository,
 * and following them would answer a different question. Everything the gate
 * claims to walk — relative paths, the `@/` alias, workspace packages — must
 * resolve or be reported.
 */
export function createResolver({ root = REPO_ROOT, packages = readWorkspacePackages(root) } = {}) {
  const siteDir = path.join(root, SITE_DIR);
  return function resolve(spec, fromFile) {
    if (spec.startsWith('.')) {
      const file = resolveFile(path.resolve(path.dirname(fromFile), spec));
      return file ? { kind: 'file', file } : { kind: 'unresolved', why: 'relative specifier' };
    }
    if (spec.startsWith('@/')) {
      const file = resolveFile(path.join(siteDir, spec.slice(2)));
      return file ? { kind: 'file', file } : { kind: 'unresolved', why: 'the `@/` site alias' };
    }
    const m = /^(@[^/]+\/[^/]+|[^@./][^/]*)(?:\/(.+))?$/.exec(spec);
    if (!m) return { kind: 'external' };
    const [, name, subpath] = m;
    const dir = packages.get(name);
    if (!dir) return { kind: 'external' };
    return packageEntry(dir, subpath);
  };
}

// ---------------------------------------------------------------------------
// Import extraction
// ---------------------------------------------------------------------------

/**
 * MDX with its fenced code blocks blanked, line count preserved.
 *
 * A fence opens with three or more backticks or tildes and closes with the same
 * character; the content between them is documentation, not module graph.
 */
export function maskFences(mdx) {
  let fence = null;
  return mdx
    .split('\n')
    .map((line) => {
      const opener = /^\s*(`{3,}|~{3,})/.exec(line);
      if (fence === null) {
        if (opener) {
          fence = opener[1][0];
          return '';
        }
        return line;
      }
      if (opener && opener[1][0] === fence) fence = null;
      return '';
    })
    .join('\n');
}

/**
 * The STATIC module specifiers a source pulls in eagerly.
 *
 * Deliberately excluded, each for its own reason:
 *
 *   - `import type` / `export type` — erased, so no graph is pulled. A bare
 *     `import { type X } from 'y'` is NOT excluded: under `verbatimModuleSyntax`
 *     it keeps a side-effect load, and over-counting is the safe direction here.
 *   - `import('x')` — the lazy form. `PluginLoader` is built on it precisely so
 *     those graphs stay OFF this route; counting them would erase the
 *     distinction this gate exists to police.
 *
 * Statements are anchored to the start of a line, which is where every module-
 * scope import in this tree sits. That is what keeps a JSX text node or an MDX
 * sentence that happens to contain the word `import` from fabricating an edge.
 */
export function extractImports(source, { mdx = false } = {}) {
  const text = mdx ? maskFences(source) : maskComments(source);
  const specs = [];
  const bound = /^[ \t]*(import|export)\s+([^;'"]*?)\bfrom\s*['"]([^'"]+)['"]/gm;
  let m;
  while ((m = bound.exec(text)) !== null) {
    if (/^\s*type\b/.test(m[2])) continue;
    specs.push({ spec: m[3], index: m.index });
  }
  const sideEffect = /^[ \t]*import\s*['"]([^'"]+)['"]/gm;
  while ((m = sideEffect.exec(text)) !== null) specs.push({ spec: m[1], index: m.index });
  return specs.sort((a, b) => a.index - b.index).map(({ spec, index }) => ({
    spec,
    line: text.slice(0, index).split('\n').length,
  }));
}

/** The workspace packages the registrar names, in file order. */
export function readDeclared(registrarPath) {
  const source = fs.readFileSync(registrarPath, 'utf8');
  // maskComments is doing real work here: this file's header QUOTES
  // `import { ObjectForm } from '@object-ui/plugin-form'` in prose, and an
  // unmasked scan reads that sentence as a declaration.
  return extractImports(source);
}

// ---------------------------------------------------------------------------
// The graph
// ---------------------------------------------------------------------------

/**
 * Crawl every module reachable from `seeds`, recording the edges rather than
 * only the set. One crawl answers every reachability question below without
 * re-reading a file, and the recorded edges are what let a green run print WHY
 * a package is free instead of asserting that it is.
 */
export function crawl({ seeds, resolve }) {
  const edges = new Map();
  const unresolved = [];
  const queue = [...seeds];
  const seen = new Set(seeds);
  while (queue.length) {
    const file = queue.shift();
    const out = [];
    edges.set(file, out);
    if (!PARSED.has(path.extname(file))) continue;
    let source;
    try {
      source = fs.readFileSync(file, 'utf8');
    } catch (error) {
      unresolved.push({ spec: file, from: '(seed)', why: `unreadable: ${error.message}` });
      continue;
    }
    for (const { spec, line } of extractImports(source, { mdx: file.endsWith('.mdx') })) {
      const target = resolve(spec, file);
      if (target.kind === 'external') continue;
      if (target.kind === 'unresolved') {
        unresolved.push({ spec, from: file, line, why: target.why });
        continue;
      }
      out.push(target.file);
      if (!seen.has(target.file)) {
        seen.add(target.file);
        queue.push(target.file);
      }
    }
  }
  return { edges, unresolved };
}

/**
 * Breadth-first reachability over an already-crawled graph.
 *
 * `blocked` files are not entered AND not reported: that is how the base graph
 * is taken — the route exactly as it would be with the registrar's import list
 * deleted, everything else still walked.
 */
export function reachable({ edges, roots, blocked = new Set() }) {
  const seen = new Set();
  const via = new Map();
  const queue = [];
  for (const root of roots) {
    if (blocked.has(root) || seen.has(root)) continue;
    seen.add(root);
    queue.push(root);
  }
  while (queue.length) {
    const file = queue.shift();
    for (const next of edges.get(file) ?? []) {
      if (blocked.has(next) || seen.has(next)) continue;
      seen.add(next);
      via.set(next, file);
      queue.push(next);
    }
  }
  return { files: seen, via };
}

/** name -> directory, as a longest-prefix lookup from a file to its package. */
function packageOfFile(packages) {
  const entries = [...packages].map(([name, dir]) => [name, dir + path.sep]);
  return (file) => {
    for (const [name, prefix] of entries) if (file.startsWith(prefix)) return name;
    return null;
  };
}

// ---------------------------------------------------------------------------
// The model
// ---------------------------------------------------------------------------

/**
 * Everything the three verdicts are computed from, taken once.
 *
 * `root` is a parameter so the unit test can drive the whole thing over a
 * fixture tree — including a tree where the answer must be RED. A gate whose
 * failing direction is only ever asserted by reading it is not verified.
 *
 * The `ledger` parameter is typed as a plain record rather than left to be
 * inferred from {@link MEASURED_PAYLOAD}: inference would freeze the fixture
 * ledger out of the signature (`allowJs` reads the default's literal keys as
 * the type), and a test that cannot pass its own ledger cannot exercise the
 * ledger halves at all.
 *
 * @param {{ root?: string, ledger?: Record<string, string> }} [options]
 */
export function analyse({ root = REPO_ROOT, ledger = MEASURED_PAYLOAD } = {}) {
  const packages = readWorkspacePackages(root);
  const resolve = createResolver({ root, packages });
  const toPackage = packageOfFile(packages);
  const registrar = path.join(root, REGISTRAR);

  const entrySeeds = ROUTE_ENTRIES.map((rel) => path.join(root, rel)).filter((file) =>
    fs.existsSync(file),
  );
  const missingEntries = ROUTE_ENTRIES.filter((rel) => !fs.existsSync(path.join(root, rel)));

  const mdxDir = path.join(root, MDX_CONTENT_DIR);
  const mdxSeeds = fs.existsSync(mdxDir) ? listMdx(mdxDir) : [];

  const ledgerNames = Object.keys(ledger);
  const ledgerSeeds = new Map();
  const ledgerUnresolved = [];
  for (const name of ledgerNames) {
    const dir = packages.get(name);
    if (!dir) {
      ledgerUnresolved.push({ spec: name, from: '(ledger)', why: 'not a workspace package' });
      continue;
    }
    const entry = packageEntry(dir, undefined);
    if (entry.kind !== 'file') {
      ledgerUnresolved.push({ spec: name, from: '(ledger)', why: entry.why });
      continue;
    }
    ledgerSeeds.set(name, entry.file);
  }

  const declared = readDeclared(registrar);
  const declaredSeeds = new Map();
  for (const { spec } of declared) {
    const dir = packages.get(spec);
    if (!dir) continue;
    const entry = packageEntry(dir, undefined);
    if (entry.kind === 'file') declaredSeeds.set(spec, entry.file);
  }

  const seeds = [
    ...entrySeeds,
    ...mdxSeeds,
    registrar,
    ...ledgerSeeds.values(),
    ...declaredSeeds.values(),
  ];
  const { edges, unresolved } = crawl({ seeds: [...new Set(seeds)], resolve });

  const routeRoots = [...entrySeeds, ...mdxSeeds];
  const full = reachable({ edges, roots: routeRoots });
  const blocked = new Set([registrar]);
  const base = reachable({ edges, roots: routeRoots, blocked });
  const withLedger = reachable({
    edges,
    roots: [...routeRoots, ...ledgerSeeds.values()],
    blocked,
  });

  const packagesIn = (files) => {
    const names = new Set();
    for (const file of files) {
      const name = toPackage(file);
      if (name) names.add(name);
    }
    return names;
  };

  return {
    root,
    ledger,
    packages,
    registrar,
    declared,
    declaredSeeds,
    ledgerSeeds,
    ledgerUnresolved,
    missingEntries,
    routeRootCount: routeRoots.length,
    mdxCount: mdxSeeds.length,
    edges,
    unresolved,
    full,
    base,
    withLedger,
    basePackages: packagesIn(base.files),
    reachablePackages: packagesIn(withLedger.files),
    toPackage,
  };
}

function listMdx(dir, acc = []) {
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) listMdx(full, acc);
    else if (entry.name.endsWith('.mdx')) acc.push(full);
  }
  return acc;
}

// ---------------------------------------------------------------------------
// The three halves
// ---------------------------------------------------------------------------

/**
 * HALF 1 — every package the registrar names is accounted for.
 *
 * `recorded` and `free` are both passes and are reported separately, because
 * they are different claims: one says "argued for in a card", the other says
 * "measured to add nothing". Collapsing them would hide the day a FREE package
 * quietly became payload.
 */
export function evaluateDeclared(model) {
  const recorded = [];
  const free = [];
  const newGraph = [];

  for (const { spec, line } of model.declared) {
    if (Object.hasOwn(model.ledger, spec)) {
      recorded.push({ spec, line, reason: model.ledger[spec] });
      continue;
    }
    if (!model.packages.has(spec)) {
      newGraph.push({ spec, line, why: 'not a workspace package — its graph cannot be weighed here at all' });
      continue;
    }
    if (model.reachablePackages.has(spec)) {
      const entry = model.declaredSeeds.get(spec);
      free.push({ spec, line, via: model.withLedger.via.get(entry) ?? null });
      continue;
    }
    newGraph.push({ spec, line, why: 'nothing else on the route imports it' });
  }

  const rel = (file) => (file ? path.relative(model.root, file) : 'a route entry');
  if (newGraph.length) {
    return {
      status: 'fail',
      recorded,
      free,
      newGraph,
      message:
        `${newGraph.length} package(s) named in ${REGISTRAR} add a NEW graph to the ` +
        `/docs/[[...slug]] eager closure:\n` +
        newGraph.map((e) => `     ${e.spec}  (line ${e.line}) — ${e.why}`).join('\n') +
        `\n   That route is shared by every docs page, and the budget over it ` +
        `(objectui#4616's +50% stop condition) has no instrument — which is why this ` +
        `is a review event and not a number. Either reach the code through a package the ` +
        `route already carries, or argue for the payload and record it in MEASURED_PAYLOAD ` +
        `in scripts/check-docs-route-eager-closure.mjs with what it is for.`,
    };
  }

  return {
    status: 'pass',
    recorded,
    free,
    newGraph,
    message:
      `all ${model.declared.length} packages named in ${REGISTRAR} are accounted for: ` +
      `${recorded.length} recorded payload, ${free.length} already reachable ` +
      `(${free.map((e) => `${e.spec} <- ${rel(e.via)}`).join(', ') || 'none'}).`,
  };
}

/**
 * HALF 2 — the ledger still describes the tree.
 *
 * An entry that is no longer named by the registrar is dead weight that would
 * pardon a future re-import without anyone arguing for it again; an entry that
 * has become reachable on its own is a claim the tree has outgrown. Both shrink
 * the ledger, and both are the author's to make deliberately.
 */
export function evaluateLedger(model) {
  const named = new Set(model.declared.map((d) => d.spec));
  const stale = Object.keys(model.ledger).filter((name) => !named.has(name));
  const noLongerPayload = [...model.ledgerSeeds.keys()].filter((name) =>
    model.basePackages.has(name),
  );

  const problems = [];
  if (stale.length) {
    problems.push(
      `${stale.length} entr${stale.length === 1 ? 'y is' : 'ies are'} no longer named by the ` +
        `registrar (${stale.join(', ')}) — delete them, or a re-added import inherits a ` +
        `pardon nobody argued for.`,
    );
  }
  if (noLongerPayload.length) {
    problems.push(
      `${noLongerPayload.length} entr${noLongerPayload.length === 1 ? 'y is' : 'ies are'} ` +
        `now reachable from the route WITHOUT the registrar (${noLongerPayload.join(', ')}) — ` +
        `they are no longer payload, so the ledger overstates. Delete the entries; the ` +
        `packages will classify as FREE on their own.`,
    );
  }

  return problems.length
    ? { status: 'fail', message: `MEASURED_PAYLOAD has drifted:\n     ${problems.join('\n     ')}` }
    : {
        status: 'pass',
        message:
          `MEASURED_PAYLOAD is honest: all ${model.ledgerSeeds.size} entries are still named by ` +
          `the registrar and none is reachable from the route any other way.`,
      };
}

/**
 * HALF 3 — the gauge itself.
 *
 * This is the half that answers "could this gate ever go red?". Each case is a
 * way the reachability computation could return "everything is reachable" — or
 * judge a file nothing loads — while every other line of output still read like
 * a pass.
 */
export function evaluateGauge(model) {
  const problems = [];

  if (model.missingEntries.length) {
    problems.push(
      `ROUTE_ENTRIES names ${model.missingEntries.length} file(s) that do not exist ` +
        `(${model.missingEntries.join(', ')}) — the route moved and this gate is walking a ` +
        `graph smaller than the real one.`,
    );
  }

  const unresolved = [...model.unresolved, ...model.ledgerUnresolved];
  if (unresolved.length) {
    const shown = unresolved.slice(0, 10).map((u) => {
      const from = u.from === '(ledger)' || u.from === '(seed)' ? u.from : path.relative(model.root, u.from);
      return `${u.spec} <- ${from}${u.line ? `:${u.line}` : ''} (${u.why})`;
    });
    problems.push(
      `${unresolved.length} specifier(s) this gate must resolve did not:\n       ` +
        shown.join('\n       ') +
        (unresolved.length > shown.length ? `\n       …and ${unresolved.length - shown.length} more` : '') +
        `\n     Every one is a subgraph that silently reads as UNREACHABLE, so a package ` +
        `behind it would be reported as a new graph — or, if the failure is on the other ` +
        `side, would never be reported at all.`,
    );
  }

  if (!model.full.files.has(model.registrar)) {
    problems.push(
      `${REGISTRAR} is NOT reachable from the /docs/[[...slug]] route entries. This gate ` +
        `judges a file the route it names does not load, so its verdict is about nothing. ` +
        `On b116a0684 the only path was content/docs/guide/schema-catalog.mdx -> ` +
        `SchemaCatalogIndex -> SchemaThumbnail; if that chain was deliberately cut, this ` +
        `gate has to be re-derived rather than relaxed.`,
    );
  }

  if (!model.mdxCount) {
    problems.push(
      `no MDX modules were found under ${MDX_CONTENT_DIR} — the compiled docs pages are ` +
        `most of this route's graph, and without them the closure is not the route's.`,
    );
  }

  const outside = [...model.packages.keys()].filter((name) => !model.reachablePackages.has(name));
  if (!outside.length) {
    problems.push(
      `every one of the ${model.packages.size} workspace packages reads as reachable. A ` +
        `traversal that reaches everything cannot distinguish a new graph from a free one, ` +
        `so this gate would pass on every input — the shape it exists to rule out.`,
    );
  }

  return problems.length
    ? { status: 'error', outside, message: `the gauge is not trustworthy:\n     ${problems.join('\n     ')}` }
    : {
        status: 'pass',
        outside,
        message:
          `gauge: ${model.edges.size} modules crawled from ${model.routeRootCount} route roots ` +
          `(${model.mdxCount} MDX), every specifier resolved, the registrar is on the route, and ` +
          `${outside.length} of ${model.packages.size} workspace packages stay OUTSIDE the ` +
          `closure — so the traversal still discriminates.`,
      };
}

