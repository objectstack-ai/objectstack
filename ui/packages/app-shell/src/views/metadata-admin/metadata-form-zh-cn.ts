/**
 * zh-CN `metadataForms` entries for the spec authoring forms this console reads
 * from its OWN copy of `@objectstack/spec` — the strings {@link
 * ./metadata-form-i18n.ts} overlays onto them. Data only, with no runtime
 * import: the Pending changes sheet reads it on the console's eager graph.
 *
 * ## Where the words come from
 *
 * Copied, leaf for leaf, from the platform's canonical zh-CN bundle for the
 * same forms (`@objectstack/platform-objects`, the
 * `zh-CN.metadata-forms.generated.ts` that `/api/v1/meta/types` localizes
 * these forms with), so a form reads the same words whether the server
 * localized it or this console did. A leaf the platform has not translated
 * (still the English source) is left out: the overlay then returns the spec's
 * own English for it, as it does for every type it does not name. The one
 * exception is a leaf a curated inspector SHOWS that the platform has no zh
 * for; it is hand-worded here and marked so at its row.
 *
 * ## Two depths, by who renders the form
 *
 *  - `view`, `page`, `report` — the curated inspectors render these forms
 *    from the bundled spec, so every section and field string is here: label,
 *    description, help text, placeholder. (`dashboard` is the fourth such
 *    form; its hand-worded entries live in `./metadata-form-i18n.ts`.)
 *  - every other `METADATA_FORM_REGISTRY` type — its inspector renders the
 *    form the server served, already localized. The one reader of these forms
 *    on this side is the Pending changes sheet, which names a changed property
 *    by its form row's label, so these carry the type label and field labels
 *    only.
 *
 * ⛔ The composite rule in `./metadata-form-i18n.ts` holds here too: a
 * `composite` / `repeater` / `record` field the form declares no `fields` for
 * gets its sub-fields SYNTHESIZED from the children named here, so no entry
 * names a child of such a field.
 */

