/**
 * Does the record's state leave its edit form with nothing to edit?
 *
 * The record page's Edit opens a form whose fields each resolve read-only
 * through `resolveFieldRuleState` (`@object-ui/core`): a server-computed
 * field, or a `readonlyWhen` the record satisfies. When every field the form draws
 * resolves read-only, the form opens with no control and an active submit
 * that changes nothing (objectstack#32756). This answers that question with
 * the form's own pieces: its system-field pass (`filterSystemFields` from
 * `@object-ui/plugin-form`) for which fields it draws, and its field-rule
 * evaluator for each verdict, so the header and the form cannot disagree
 * about a field. ⛔ It never evaluates a predicate itself.
 *
 * It answers `true` only when ALL of these hold, and fails open otherwise:
 *
 *  - at least one drawn field is locked by its `readonlyWhen`, so the lock is
 *    the record's state, which is what the header's reason names;
 *  - every drawn field resolves read-only, over the object's whole field map,
 *    a superset of any curated form view's sections, so a writable field
 *    anywhere keeps Edit live;
 *  - the edit form view declares no inline child collection (`subforms`),
 *    whose rows the form still edits whatever the header fields say.
 *
 * A predicate that faults resolves to its fail-open verdict (writable), as in
 * the form, so a broken rule never greys Edit.
 */

import { isExpressionComputedField, resolveFieldRuleState } from '@object-ui/core';
import { filterSystemFields, isAutoGeneratedFieldType } from '@object-ui/plugin-form';
import type { FormField } from '@object-ui/types';
import { resolveFormViewLayout, type ObjectDefinitionForFormView } from './recordFormNavigation.js';

/** The slice of a served object definition this reads. */
export type EditFormLockObject = ObjectDefinitionForFormView & {
  fields?: Record<string, unknown> | Array<unknown> | null;
};

interface FieldEntry {
  name: string;
  def: Record<string, any>;
}

function fieldEntries(fields: EditFormLockObject['fields']): FieldEntry[] {
  if (!fields) return [];
  if (Array.isArray(fields)) {
    return fields
      .filter((f): f is Record<string, any> => !!f && typeof f === 'object' && typeof (f as any).name === 'string')
      .map((f) => ({ name: f.name as string, def: f }));
  }
  return Object.entries(fields)
    .filter(([, f]) => !!f && typeof f === 'object')
    .map(([name, f]) => ({ name, def: f as Record<string, any> }));
}

export function editFormLockedByState(
  objectDef: EditFormLockObject | null | undefined,
  record: Record<string, unknown> | null | undefined,
  scope?: Record<string, unknown>,
): boolean {
  if (!objectDef || !record) return false;
  if (resolveFormViewLayout(objectDef, 'edit').subforms) return false;

  const declared = fieldEntries(objectDef.fields);
  // The fields the form draws: the form's own system-field pass drops the
  // platform-managed columns (`id`, audit, ownership), `hidden` and static
  // `readonly` fields before anything renders, so none of them can keep Edit
  // live by being writable on paper.
  const byName: Record<string, Record<string, any>> = {};
  for (const { name, def } of declared) byName[name] = def;
  const drawn = new Set(
    filterSystemFields(declared.map(({ name }) => ({ name }) as FormField), { fields: byName }).map((f) => f.name),
  );
  const entries = declared.filter(({ name }) => drawn.has(name));
  // The form's own seeding: every declared field present as `null` under the
  // stored row, so a predicate naming an unset column compares against `null`.
  const ruleRecord: Record<string, unknown> = {};
  for (const { name } of declared) ruleRecord[name] = null;
  for (const [k, v] of Object.entries(record)) if (v !== undefined) ruleRecord[k] = v;

  let shown = 0;
  let lockedByRule = 0;
  for (const { name, def } of entries) {
    // A server-computed field (a stored `expression`, a formula, summary or
    // auto-number) is drawn as its read face on an edit form: never writable,
    // and never the record's state either.
    const staticReadonly =
      isExpressionComputedField(def) || (typeof def.type === 'string' && isAutoGeneratedFieldType(def.type));
    const state = resolveFieldRuleState(
      { visibleWhen: def.visibleWhen, readonlyWhen: def.readonlyWhen },
      ruleRecord,
      { readonly: staticReadonly, name },
      ruleRecord,
      scope,
      `field '${name}'`,
    );
    if (!state.visible) continue;
    shown += 1;
    if (!state.readonly) return false;
    if (!staticReadonly) lockedByRule += 1;
  }
  return shown > 0 && lockedByRule > 0;
}
