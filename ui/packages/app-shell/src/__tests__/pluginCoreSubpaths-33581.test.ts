/**
 * The console shell takes the form and view helpers from the side-effect-free
 * `/core` subpaths, never from the package entries (objectstack#33581).
 *
 * `@object-ui/plugin-form` and `@object-ui/plugin-view` register their
 * renderers when their entry is evaluated, and each entry reaches every surface
 * of its package. A named import of one pure helper from an entry, in any
 * module the first load reaches, puts the whole package back into every first
 * load; nothing else says so, because the console's eager-closure budget is far
 * coarser than one plugin chunk.
 *
 * Two pins:
 *  - no shell or console source imports, from an entry, a value name its
 *    `/core` subpath exports (the names are read from the subpath itself, so a
 *    helper added there is covered the day it is added);
 *  - the always-eager shell modules that draw a form or a view import nothing
 *    from either entry by value: their components load through `lazy()`
 *    (`views/lazyFormSurfaces.tsx`) or through the console's lazy stubs.
 *
 * ⚠ A SOURCE SCAN: it reads import declarations, not the bundle. The built
 * graph is the console's `dist/eager-closure.json`; this file keeps the edges
 * that graph was measured on from coming back one import at a time.
 */

import { describe, it, expect } from 'vitest';
import { readFileSync, readdirSync, statSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import * as formCore from '@object-ui/plugin-form/core';
import * as viewCore from '@object-ui/plugin-view/core';
// @ts-expect-error — plain-JS shared helper, intentionally untyped (`allowJs: false`)
import { maskComments } from '../../../../scripts/js-comment-mask.mjs';

const mask: (source: string) => string = maskComments;

const here = path.dirname(fileURLToPath(import.meta.url));
const SHELL_SRC = path.resolve(here, '..');
const CONSOLE_SRC = path.resolve(here, '../../../../apps/console/src');

const ENTRIES = {
  '@object-ui/plugin-form': new Set(Object.keys(formCore)),
  '@object-ui/plugin-view': new Set(Object.keys(viewCore)),
} as const;
type Entry = keyof typeof ENTRIES;

function sourceFiles(dir: string): string[] {
  const out: string[] = [];
  for (const name of readdirSync(dir)) {
    const full = path.join(dir, name);
    if (statSync(full).isDirectory()) {
      if (name === '__tests__' || name === '__mocks__' || name === 'node_modules') continue;
      out.push(...sourceFiles(full));
    } else if (/\.(ts|tsx)$/.test(name) && !/\.(test|spec)\.tsx?$/.test(name) && !name.endsWith('.d.ts')) {
      out.push(full);
    }
  }
  return out;
}

interface EntryImport {
  file: string;
  entry: Entry;
  /** Value names; `null` for a bare side-effect import. */
  values: string[] | null;
}

const IMPORT_RE = /\bimport\s+(type\s+)?([\s\S]*?)\s*from\s*['"]([^'"]+)['"]|\bimport\s+['"]([^'"]+)['"]/g;

function entryImports(file: string): EntryImport[] {
  const source = mask(readFileSync(file, 'utf8'));
  const found: EntryImport[] = [];
  for (const m of source.matchAll(IMPORT_RE)) {
    const specifier = (m[3] ?? m[4]) as string;
    if (!(specifier in ENTRIES)) continue;
    const entry = specifier as Entry;
    if (m[4]) { found.push({ file, entry, values: null }); continue; }
    if (m[1]) continue; // `import type { … }` is erased
    const clause = m[2] as string;
    const named = /\{([\s\S]*)\}/.exec(clause)?.[1] ?? '';
    const values = named
      .split(',')
      .map((s) => s.trim())
      .filter((s) => s !== '' && !s.startsWith('type '))
      .map((s) => s.split(/\s+as\s+/)[0] as string);
    const defaultOrNs = clause.replace(/\{[\s\S]*\}/, '').replace(/,/g, '').trim();
    if (defaultOrNs !== '') values.push(defaultOrNs);
    found.push({ file, entry, values });
  }
  return found;
}

const FILES = [...sourceFiles(SHELL_SRC), ...sourceFiles(CONSOLE_SRC)];
const rel = (file: string) => path.relative(path.resolve(here, '../../../..'), file).split(path.sep).join('/');

describe('the form and view helpers come from the /core subpaths (objectstack#33581)', () => {
  it('reads real subpaths and a real tree (floors)', () => {
    // The helpers the console shell measured on: each subpath must still carry them.
    for (const name of ['filterSystemFields', 'isAutoGeneratedFieldType', 'useInitialFieldFocus', 'resolveInlineMode']) {
      expect(ENTRIES['@object-ui/plugin-form'].has(name), name).toBe(true);
    }
    for (const name of ['deriveRecordSurface', 'deriveRecordFlowSurface', 'overlayWidthFor', 'toFilterGroup']) {
      expect(ENTRIES['@object-ui/plugin-view'].has(name), name).toBe(true);
    }
    expect(FILES.length).toBeGreaterThan(500);
    // The scan must see the subpath imports it protects, or it is reading nothing.
    const coreImporters = FILES.filter((f) => /from\s*['"]@object-ui\/plugin-(form|view)\/core['"]/.test(readFileSync(f, 'utf8')));
    expect(coreImporters.length).toBeGreaterThanOrEqual(10);
  });

  it('no shell or console source imports a /core helper from a package entry', () => {
    const offenders: string[] = [];
    for (const file of FILES) {
      for (const { entry, values } of entryImports(file)) {
        for (const name of values ?? []) {
          if (ENTRIES[entry].has(name)) offenders.push(`${rel(file)}: ${name} from '${entry}' (use '${entry}/core')`);
        }
      }
    }
    expect(offenders).toEqual([]);
  });

  it('the always-eager modules that draw a form or a view import neither entry by value', () => {
    const EAGER = [
      'packages/app-shell/src/console/AppContent.tsx',
      'packages/app-shell/src/hooks/useActionModal.tsx',
      'packages/app-shell/src/views/ScreenView.tsx',
      'packages/app-shell/src/views/lazyFormSurfaces.tsx',
      'packages/app-shell/src/providers/MetadataProvider.tsx',
      'packages/app-shell/src/views/ActionParamDialog.tsx',
      'packages/app-shell/src/views/recordDrawerStack.tsx',
      'packages/app-shell/src/views/userFilterUrlState.ts',
      'apps/console/src/components/FormPage.tsx',
      'apps/console/src/register-plugins.ts',
    ];
    const offenders: string[] = [];
    for (const r of EAGER) {
      const file = path.resolve(here, '../../../..', r);
      for (const { entry, values } of entryImports(file)) {
        offenders.push(`${r}: ${values === null ? 'bare import' : values.join(', ')} from '${entry}'`);
      }
    }
    expect(offenders).toEqual([]);
  });
});
