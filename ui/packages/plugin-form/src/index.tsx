/**
 * The CREATE-payload rule this package owns, published for the OTHER form
 * renderer (objectui#6059).
 *
 * `omitServerResolvedDefaults` is a pure function over a values object and an
 * object schema — no React, no registry, no container — and it is the
 * COMPOSITION of two `@object-ui/core` predicates (`isRuntimeDefault` AND
 * `isMissingForRequired`, on create only) rather than a third opinion about
 * either. It stayed module-private through the whole #4047 / #4068 / #4069 /
 * #4085 / #5683 / #5727 / #5883 chain, so the console's `FormPage` — the SECOND
 * form renderer in this repo — had to spell that composition out by hand for
 * #5883, and the next renderer would have had to as well. Neither PREDICATE was
 * ever copied (both live in `@object-ui/core` precisely so they cannot fork),
 * but two hand-written copies of the composition are still free to disagree
 * about a case neither author had in mind. One importable function is not.
 *
 * `isRequiredInForm` travels with it because each one's docblock names the
 * other as its half: excusing a server-owned field from `required` and then
 * submitting the key anyway is not half a fix, it is no fix. A consumer able to
 * reach one and not the other can build exactly that state, which is the defect
 * #4069 and #5883 closed on the two chains separately.
 *
 * `optionListDefault` joined them for a named consumer (objectui#13049): the
 * console's public form page (`/f/:slug`) seeds its own create values and had
 * no reading of an option's `default: true`, so a required select the server
 * would default opened empty and the client refused the submit. That page now
 * calls the very function `schemaDefaultValues` calls (objectui#11914), so the
 * two renderers cannot disagree about which option is the default. It travels
 * with its parameter type, `OptionListFieldLike` (objectui#7324).
 *
 * Deliberately NOT the rest of `schemaDefaults.ts`. `seedCreateValues`,
 * `schemaDefaultValues`, `isSeedableDefault`, `isCreateFormMode` and
 * `SeedContext` are adjacent, not asked for — no consumer outside this package
 * has needed them, and every added name is published surface somebody then has
 * to keep. The public form page needed the option-list reading alone: its
 * literal-default and runtime-default rules were already its own (#5727), and
 * the precedence gate (`defaultValue == null`) is the caller's. `isRuntimeDefault`
 * stays out for a stronger reason: it is `@object-ui/core`'s to publish, this
 * module only re-exports it for its own call sites, and a second published
 * spelling of one classifier is the very thing #4085 collapsed.
 */
export { omitServerResolvedDefaults, isRequiredInForm, optionListDefault } from './schemaDefaults';

/**
 * The `form.sections[].group` RESOLVER, published for the third form-section
 * consumer (objectui#8641).
 *
 * `resolveSectionGroupReferences` replaces every `{ group: 'x' }` section with
 * the section that group declares, and returns its input UNCHANGED — the same
 * array reference — when no section uses the reference form. It is a pure
 * function over plain data: no React, no registry, no container.
 *
 * ## Why it is published rather than copied
 *
 * `apps/console`'s `FormPage` has its OWN section builder (`buildSections`),
 * on none of this package's code path, and it read `sec.fields ?? []` — so a
 * spec-legal `{ group }` section produced a section with no label and no
 * fields, measured in the DOM as an empty bordered card with zero inputs on
 * both the internal `/forms/:name` and public `/f/:slug` routes. That is the
 * silent-drop class objectui#7051 closed HERE, arriving at a renderer #7051's
 * fix could not reach.
 *
 * The standing constraint of objectui#7051 / objectstack#13855 is that no
 * assembly rule may be re-implemented on the objectui side — not declared
 * order, not the empty-group drop, not the ungrouped trailing bucket, not the
 * collapse / `visibleWhen` passthrough. Every one of those comes from
 * `deriveFieldGroupLayout` (ADR-0085 §5) through this package's ONE adapter,
 * `deriveFieldGroupSections`, which this resolver calls. A consumer that
 * reached for `deriveFieldGroupLayout` directly would have to re-spell the
 * `collapse` enum -> `{ collapsible, collapsed }` mapping and the `visibleWhen`
 * passthrough to land on a section shape, which is that constraint's exact
 * prohibition. So the importable resolver is the only arm that keeps one
 * assembler and one behaviour for all three consumers.
 *
 * This is the same surface decision as objectui#6059's create-payload pair,
 * for the same file, and it is deliberately as small: the resolver and the
 * options type its signature requires (objectui#7324's rule — a consumer must
 * be able to NAME what it passes; a type adds no runtime surface).
 * `hasSectionGroupReference` stays module-private because the resolver already
 * answers it by returning its input unchanged, and `resetSectionGroupReports`
 * stays private because it is this package's own test seam.
 */
export { resolveSectionGroupReferences } from './sectionGroups';
export type { ResolveSectionGroupsOptions } from './sectionGroups';

