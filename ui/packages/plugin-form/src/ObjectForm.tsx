/**
 * Props of the `ObjectForm` React component.
 *
 * Renamed off the bare `ObjectFormProps` (objectui#4650): from 17.0.0
 * `@objectstack/spec/ui` owns that name, where it is the AUTHORED props
 * document of the `object-form` element — `z.input<typeof
 * ObjectFormPropsSchema>`, i.e. serialisable authoring keys only. This is the
 * RENDERER's props: a live `dataSource`, submit/cancel callbacks and imperative
 * handles, none of which can exist in authored metadata. Two layers under one
 * word, resolved the way this repo already resolved it for `PageHeaderProps` ->
 * `PageHeaderComponentProps` (app-shell) and the `Record*ComponentProps` family
 * in `@object-ui/types`.
 *
 * The barrel keeps `ObjectFormProps` as a deprecated alias of this type, so no
 * importer breaks. Tripwire: `__tests__/spec-symbol-4650.test.ts`.
 */
export interface ObjectFormComponentProps {
  /**
   * The schema configuration for the form
   */
  schema: ObjectFormSchema;
  
  /**
   * Data source (ObjectQL or ObjectStack adapter)
   * Optional when using inline field definitions (customFields or fields array with field objects)
   */
  dataSource?: DataSource;
  
  /**
   * Additional CSS class
   */
  className?: string;
}

/**
 * Fold the structured, spec-aligned `buttons`/`defaults` surface
 * (`@objectstack/spec` FormViewSchema; framework#1894 / objectstack-ai/objectstack#2998) down onto the
 * flat renderer props ObjectForm and its variants read
 * (`showSubmit`/`submitText`/`showCancel`/`cancelText`/`showReset`/
 * `initialValues`). This is the objectui-side consumer of those spec keys — it
 * is what lets them flip `experimental → live` in the spec liveness ledger.
 *
 * Spec is the authored surface, but an explicitly-set flat key still wins so
 * existing metadata that authored the deprecated flat keys is unchanged.
 * Returns the input untouched when neither structured key is present (the
 * common case), so there is no allocation on the hot path.
 */
function foldFormButtons(schema: ObjectFormComponentProps['schema']): ObjectFormComponentProps['schema'] {
  const buttons = (schema as { buttons?: ObjectFormSchema['buttons'] }).buttons;
  const defaults = (schema as { defaults?: Record<string, any> }).defaults;
  if (!buttons && !defaults) return schema;
  const s = schema as Record<string, any>;
  const out: Record<string, any> = { ...s };
  if (buttons?.submit?.show !== undefined && s.showSubmit === undefined) out.showSubmit = buttons.submit.show;
  if (buttons?.submit?.label != null && s.submitText === undefined) out.submitText = buttons.submit.label;
  if (buttons?.cancel?.show !== undefined && s.showCancel === undefined) out.showCancel = buttons.cancel.show;
  if (buttons?.cancel?.label != null && s.cancelText === undefined) out.cancelText = buttons.cancel.label;
  if (buttons?.reset?.show !== undefined && s.showReset === undefined) out.showReset = buttons.reset.show;
  if (defaults && s.initialValues === undefined) out.initialValues = defaults;
  return out as ObjectFormComponentProps['schema'];
}

/**
 * The seven members `ComponentPropsMap['object-form']` in `@objectstack/spec`
 * declares as `I18nLabel`: a plain string or an inline per-locale map such as
 * `{ en: 'Save order', 'zh-CN': '保存订单' }` (objectui#10993).
 */
const OBJECT_FORM_LABEL_KEYS = [
  'title',
  'description',
  'submitText',
  'cancelText',
  'nextText',
  'prevText',
  'successMessage',
] as const;
type ObjectFormLabelKey = (typeof OBJECT_FORM_LABEL_KEYS)[number];

/**
 * `ObjectFormSchema` as every presentation below reads it: the seven
 * `I18nLabel` members already resolved to a string. A homomorphic mapped type
 * rather than `Omit`, because `BaseSchema`'s index signature made `Omit`
 * collapse to that signature and drop every declared member (until
 * objectui#8347 removed it).
 */
type LocalizedObjectFormSchema = {
  [K in keyof ObjectFormSchema]: K extends ObjectFormLabelKey ? string : ObjectFormSchema[K];
};

/**
 * Resolve the seven `I18nLabel` members against the active UI language — the
 * source `ObjectMetricWidget` and `MasterDetailForm` resolve their own
 * `I18nLabel` members against — before any presentation reads them.
 *
 * Read raw, a map was a React child in every presentation that renders one
 * (`submitText` / `cancelText` on the form's buttons, `nextText` / `prevText`
 * on the wizard's, `title` / `description` as the drawer and modal headings)
 * and threw "Objects are not valid as a React child", taking the whole form
 * down; `successMessage` went into the success toast.
 *
 * Only the map arm is touched: a string, or any value that is not an object,
 * is handed on exactly as authored. A map with no usable entry resolves to
 * `undefined`, so each presentation's own default ('Create', 'Cancel', 'Next',
 * …) shows. Returns its input untouched when no member is a map, so there is
 * no allocation on the hot path.
 */
function localizeFormLabels(
  schema: ObjectFormComponentProps['schema'],
  language: string,
): LocalizedObjectFormSchema {
  let out: Record<string, unknown> | null = null;
  for (const key of OBJECT_FORM_LABEL_KEYS) {
    const value: unknown = schema[key];
    if (value === null || typeof value !== 'object') continue;
    out ??= { ...schema };
    out[key] = pickLocalized(value, language) || undefined;
  }
  return (out ?? schema) as LocalizedObjectFormSchema;
}

/**
 * ObjectForm Component
 *
 * Renders a form for an ObjectQL object with automatic schema integration.
 *
 * @example
 * ```tsx
 * <ObjectForm
 *   schema={{
 *     type: 'object-form',
 *     objectName: 'users',
 *     mode: 'create',
 *     fields: ['name', 'email', 'status']
 *   }}
 *   dataSource={dataSource}
 * />
 * ```
 */
export const ObjectForm: React.FC<ObjectFormComponentProps> = ({
  schema: rawSchema,
  dataSource,
}) => {
  const perms = usePermissions();

  // ── `sections[].group` — the ADR-0085 §5 REFERENCE form (objectui#7051) ───
  //
  // A section may point `group` at one of the object's declared `fieldGroups`
  // instead of enumerating members (`@objectstack/spec` 17.3.0,
  // objectstack#13855). Resolving it needs the OBJECT definition, and this
  // dispatcher — unlike the six bodies below it — has never loaded one.
  //
  // It is resolved HERE, above the routing, on purpose: every variant's
  // `sections` prop is rebuilt key by key in the maps below, so a `group` left
  // in place would be dropped before any container could see it, and each
  // container would need its own copy of the resolution. One site above the
  // fork is what makes "one assembler" true for all six layouts at once —
  // including `simple`, whose section loop read `section.fields.map(...)`
  // unguarded and threw `Cannot read properties of undefined (reading 'map')`
  // on a spec-legal `{ group }` section, blanking the WHOLE form (measured on
  // this file at `origin/main`; the other five silently dropped the section
  // instead, because `buildSectionFields` spells the same read `?? []`).
  //
  // The load is gated on an authored `group` being present, so a form that
  // does not use the reference form issues no request and takes no new path.
  const needsGroupLayout = hasSectionGroupReference((rawSchema as any)?.sections);
  const canResolveGroups = typeof (dataSource as any)?.getObjectSchema === 'function';
  const [groupObjectDef, setGroupObjectDef] = useState<any>(null);
  useEffect(() => {
    if (!needsGroupLayout || !canResolveGroups) return;
    let alive = true;
    Promise.resolve((dataSource as any).getObjectSchema(rawSchema.objectName))
      .then((def: any) => { if (alive) setGroupObjectDef(def ?? null); })
      // A failed load leaves the references unresolved (their sections render
      // empty). It is deliberately NOT reported as a dangling reference: the
      // body below owns the load error for the object, and claiming the group
      // does not exist would be a second, wrong diagnosis of one failure.
      .catch(() => { if (alive) setGroupObjectDef(null); });
    return () => { alive = false; };
  }, [needsGroupLayout, canResolveGroups, dataSource, rawSchema.objectName]);

  // The UI language the seven `I18nLabel` members resolve against — see
  // `localizeFormLabels` (objectui#10993).
  const { language } = useObjectTranslation();

  // Apply field-level permissions to the entire schema (sections + flat
  // fields) BEFORE dispatching to any variant. This way all variants
  // (Tabbed/Wizard/Split/Drawer/Modal/Simple) transparently honour FLS.
  // Fail-open when no provider mounted (perms.isLoaded false).
  const schema = useMemo<LocalizedObjectFormSchema>(() => {
    // framework#1894 / objectstack-ai/objectstack#2998 (ADR-0078): the authored @objectstack/spec
    // FormViewSchema carries the structured `buttons.{submit,cancel,reset}.
    // {show,label}` + `defaults` surface, but this renderer historically read
    // only the flat `showSubmit`/`submitText`/…/`initialValues`. Fold the
    // structured shape down onto those flat props FIRST so every downstream
    // read (and every variant we dispatch `schema` into) sees it. An
    // explicitly-set flat key still wins (deprecated back-compat).
    //
    // objectui#10993: the seven `I18nLabel` members are resolved HERE, above the
    // `formType` fork, for the reason `sections[].group` is resolved above it:
    // every presentation reads them, so one site covers all of them. Folded
    // first, so a `buttons.*.label` lands on the flat key before it resolves.
    const folded = localizeFormLabels(foldFormButtons(rawSchema), language);
    // #2545: spec FormViewSchema defines `groups` as a legacy alias of
    // `sections`, and this renderer only ever consumes `sections` — normalize
    // so groups-only metadata actually renders (it used to be silently
    // ignored). Legacy shape maps `title`→`label`, `defaultCollapsed`→`collapsed`.
    const legacyGroups = (folded as any).groups;
    const base: LocalizedObjectFormSchema =
      !folded.sections?.length && Array.isArray(legacyGroups) && legacyGroups.length
        ? {
            ...folded,
            sections: legacyGroups.map((g: any) => ({
              label: g.title ?? g.label,
              description: g.description,
              collapsible: g.collapsible,
              collapsed: g.defaultCollapsed ?? g.collapsed,
              fields: g.fields ?? [],
            })),
          }
        : folded;
    /**
     * Resolve every `{ group }` section into the section that group declares.
     *
     * Returns its input UNCHANGED — same array reference — when no section
     * uses the reference form, so this memo cannot perturb any existing form.
     */
    const withGroups = (s: LocalizedObjectFormSchema) => {
      const resolved = resolveSectionGroupReferences(s.sections as any, {
        objectName: s.objectName,
        formType: s.formType,
        objectDef: groupObjectDef,
        resolvable: canResolveGroups,
      });
      return resolved === (s.sections as any) ? s : { ...s, sections: resolved as any };
    };
    if (!perms?.isLoaded) return withGroups(base);
    // ONE render gate, shared with `ModalForm` and `DrawerForm` — see
    // `fieldWriteGate.ts` for why the copy each container used to carry is the
    // defect rather than the style (`80c54122e`).
    const filterArr = (arr?: any[]) =>
      applyFieldPermissions(arr, { perms, objectName: base.objectName, mode: base.mode });
    return withGroups({
      ...base,
      fields: filterArr(base.fields as any[]),
      sections: base.sections?.map((s: any) => ({
        ...s,
        fields: filterArr(s.fields),
      })),
    } as LocalizedObjectFormSchema);
  }, [rawSchema, perms, groupObjectDef, canResolveGroups, language]);
  const { sectionLabel } = useSafeFieldLabel();
  const tSec = (s: any) =>
    s?.name ? sectionLabel(schema.objectName, s.name, s.label || s.name) : s?.label;

  // Master-detail: when the schema declares inline child collections, render as
  // a master-detail form (parent fields + child grids, persisted atomically).
  // This lets a plain form view become master-detail by config — no bespoke
  // page. Skipped in view mode (read-only detail uses related lists instead).
  // For drawer/modal formTypes we fall through to DrawerForm/ModalForm, which
  // host the master-detail form INSIDE their envelope.
  const routesToMasterDetail = !!(schema as any).subforms?.length && schema.mode !== 'view'
      && schema.formType !== 'drawer' && schema.formType !== 'modal';

  // ── objectui#6237 diagnostic, now scoped to the ONE arm still inert ────────
  // The interim diagnostic ruled on 2026-08-29 covered `tabbed` AND `wizard`,
  // the two routes that dropped an authored section `visibleWhen`. The tabbed
  // arm now HONOURS it (the map below copies the key, `TabbedForm` puts it on
  // the tab it synthesises, and the renderer evaluates it), so warning about it
  // would be a false alarm about a working feature — the same boundary the four
  // control rows of the diagnostic's pin defend. `wizard` stays inert by
  // DESIGN, not by omission: a step predicate is a different contract, not a
  // port (see `WizardStepConfig`), so its gap is still reported rather than
  // silently dropped.
  //
  // Deliberately NOT reported for the master-detail branch: that branch re-enters
  // `ObjectForm` through `MasterDetailForm`'s parent schema, which is where the
  // real layout is decided (a master-detail `wizard` parent renders `simple`,
  // which DOES honour the predicate). Reporting here as well would double-report
  // the tabbed parent and false-report the wizard one.
  const inertPredicateLayout = !routesToMasterDetail && schema.formType === 'wizard'
    ? schema.formType
    : null;
  // Joined to a string on purpose: the effect's deps must be primitives, or a
  // fresh array identity each render would re-report on every keystroke.
  const inertPredicateSections = (schema.sections ?? [])
    .filter((s: any) => s?.visibleWhen != null)
    .map((s: any) => s?.name || s?.label || '(unnamed)')
    .join(', ');
  useEffect(() => {
    if (!inertPredicateLayout || !inertPredicateSections) return;
    console.warn(sectionPredicateUnsupportedWarning(inertPredicateLayout, inertPredicateSections));
  }, [inertPredicateLayout, inertPredicateSections]);

  if (routesToMasterDetail) {
    return (
      <MasterDetailForm
        schema={{
          type: 'object-master-detail-form',
          objectName: schema.objectName,
          mode: schema.mode === 'edit' ? 'edit' : 'create',
          recordId: schema.recordId,
          // Forward prefilled header values so create-mode wizards (e.g. lead
          // conversion) seed the parent fields, not just plain forms.
          initialValues: (schema as any).initialValues,
          initialData: (schema as any).initialData,
          formType: schema.formType === 'tabbed' ? 'tabbed' : 'simple',
          sections: schema.sections as any,
          fields: schema.fields as any,
          title: schema.title,
          submitText: schema.submitText,
          cancelText: schema.cancelText,
          // Forward the host's submit-visibility so a non-persisting preview
          // can hide the master-detail Save bar (it owns the only Save here).
          showSubmit: (schema as any).showSubmit,
          details: (schema as any).subforms,
          onSuccess: schema.onSuccess,
          onError: schema.onError,
          onCancel: schema.onCancel,
          className: schema.className,
        }}
        dataSource={dataSource}
      />
    );
  }

  // Route to specialized form variant based on formType
  if (schema.formType === 'tabbed' && schema.sections?.length) {
    return (
      <TabbedForm
        schema={{
          ...schema,
          formType: 'tabbed',
          sections: schema.sections.map(s => ({
            name: s.name,
            label: tSec(s),
            description: s.description,
            columns: s.columns,
            // `?? []` because `ObjectFormSection.fields` is OPTIONAL since objectui#7051
            // — `group` is the other way a section declares its members. A `{ group }`
            // section has already been resolved into one carrying `fields` before this
            // map runs (and an unresolvable one into `fields: []`), so this default is
            // reached only by a programmatic caller sending a section with neither,
            // which the spec door refuses. These per-layout config types stay
            // `fields`-required on purpose: they are the programmatic React-mount
            // shapes, not the authorable surface, and the reference form is resolved
            // above them.
            fields: s.fields ?? [],
            // ADR-0089 section predicate (objectui#6237) — key-by-key rebuild,
            // so an uncopied key is silently dropped before TabbedForm ever
            // sees it, exactly as it was on this route until this card. The
            // split/drawer/modal maps below have carried it since #6111; this
            // is the tabbed arm joining them.
            //
            // Read WITHOUT an `as any` cast on purpose, unlike those three:
            // `ObjectFormSection.visibleWhen` is declared, so the compiler is
            // able to catch a rename here. Through a cast it would keep
            // compiling and silently copy `undefined` — the exact silent-drop
            // failure this line exists to fix.
            visibleWhen: s.visibleWhen,
            visibleWhenFault: s.visibleWhenFault,
            // ⛔ `className` / `gridClassName` are DELIBERATELY not copied here
            // or at any of the six sibling sites below — objectstack#13626,
            // maintainer ruling 2026-09-01 (director decision batch C):
            // "retire the reads".
            //
            // The two keys sit on the SDUI-only side of the authorable
            // boundary: `@objectstack/spec` deliberately does NOT declare them
            // on the form-view/section surface (see the "Deliberately NOT
            // declared" note in its `component.zod.ts`), and the
            // authorable-surface ledger carries no entry for them. They were
            // nevertheless reached off the parsed view through `as any` — the
            // boundary declared on one side and crossed on the other.
            //
            // Declaring them instead was weighed and NOT adopted: it would
            // formally invite free Tailwind strings into authored metadata,
            // the exact class the boundary exists to keep out — and per
            // ADR-0065 / ADR-0080 (rev. 2026-06-30) utility classNames in
            // runtime metadata are never scanned by the build-time Tailwind,
            // so they silently produce no CSS. If per-view styling becomes a
            // real product need it gets an explicit controlled token surface,
            // not two leaked keys.
            //
            // ⚠️ `ObjectFormSection` (this repo's own `@object-ui/types`) no
            // longer declares either key (objectui#7200), so an uncast
            // `className: s.className` fails to compile here. A CAST read —
            // the shape the seven retired sites had — still would, and JSON
            // metadata carries whatever an author wrote. The omission is
            // therefore pinned behaviourally, not by a source grep —
            // `__tests__/sectionStyleKeysRetired-13626.test.tsx`.
          })),
          defaultTab: schema.defaultTab,
          tabPosition: schema.tabPosition,
        }}
        dataSource={dataSource}
        className={schema.className}
      />
    );
  }

  if (schema.formType === 'wizard' && schema.sections?.length) {
    return (
      <WizardForm
        schema={{
          ...schema,
          formType: 'wizard',
          // Key-by-key rebuild into `WizardStepConfig`, the wizard's OWN step
          // shape: `visibleWhen` / `collapsible` / `collapsed` are deliberately
          // not copied — wizard steps carry no predicate slot and do not
          // collapse (objectui#6237 split; upgraded to a spec-door parse
          // refusal by objectstack#13622 D2, ruled 2026-08-31, so authored
          // metadata carrying them never reaches this map). The predicate drop
          // is additionally reported above for the callers the spec door
          // cannot see (programmatic SDUI, pre-tightening metadata).
          sections: schema.sections.map(s => ({
            name: s.name,
            label: tSec(s),
            description: s.description,
            columns: s.columns,
            // `?? []` — see the tabbed arm above (objectui#7051).
            fields: s.fields ?? [],
            // `className` / `gridClassName`: deliberately not copied — see the
            // tabbed arm above (objectstack#13626, ruled 2026-09-01).
          })),
          allowSkip: schema.allowSkip,
          showStepIndicator: schema.showStepIndicator,
          nextText: schema.nextText,
          prevText: schema.prevText,
          onStepChange: schema.onStepChange,
        }}
        dataSource={dataSource}
        className={schema.className}
      />
    );
  }

  if (schema.formType === 'split' && schema.sections?.length) {
    return (
      <SplitForm
        schema={{
          ...schema,
          formType: 'split',
          sections: schema.sections.map(s => ({
            name: s.name,
            label: tSec(s),
            description: s.description,
            columns: s.columns,
            // `?? []` — see the tabbed arm above (objectui#7051).
            fields: s.fields ?? [],
            // Explicit pane placement (spec FormSection.pane). This mapping
            // rebuilds each section key by key, so a key it doesn't copy is
            // silently dropped — exactly how `visibleOn` once vanished here.
            pane: s.pane,
            // ADR-0089 section predicate (#6111) — same reason as `pane` above:
            // a key this map does not copy never reaches the layout at all.
            visibleWhen: (s as any).visibleWhen,
            visibleWhenFault: s.visibleWhenFault,
            // `className` / `gridClassName`: deliberately not copied — see the
            // tabbed arm above (objectstack#13626, ruled 2026-09-01).
          })),
          splitDirection: schema.splitDirection,
          splitSize: schema.splitSize,
          splitResizable: schema.splitResizable,
        }}
        dataSource={dataSource}
        className={schema.className}
      />
    );
  }

  if (schema.formType === 'drawer') {
    // `layout` passes through unfolded: it is `vertical | horizontal` on both
    // faces since objectui#11168 slice 3 (objectui#7759 group C), and the fold
    // that mapped `inline` / `grid` away here is retired with them.
    return (
      <DrawerForm
        schema={{
          ...schema,
          formType: 'drawer',
          sections: schema.sections?.map(s => ({
            name: s.name,
            label: tSec(s),
            description: s.description,
            columns: s.columns,
            // `?? []` — see the tabbed arm above (objectui#7051).
            fields: s.fields ?? [],
            collapsible: (s as any).collapsible,
            collapsed: (s as any).collapsed,
            // ADR-0089 section predicate (#6111) — key-by-key rebuild, so an
            // uncopied key is silently dropped before DrawerForm ever sees it.
            visibleWhen: (s as any).visibleWhen,
            visibleWhenFault: s.visibleWhenFault,
            // `className`: deliberately not copied — see the tabbed arm above
            // (objectstack#13626, ruled 2026-09-01). DrawerForm's own divider
            // site stops reading it in the same pass.
          })),
          open: schema.open,
          onOpenChange: schema.onOpenChange,
          drawerSide: schema.drawerSide,
          drawerWidth: schema.drawerWidth,
        }}
        dataSource={dataSource}
        className={schema.className}
      />
    );
  }

  if (schema.formType === 'modal') {
    // `layout` passes through unfolded — see the drawer branch above.
    return (
      <ModalForm
        schema={{
          ...schema,
          formType: 'modal',
          sections: schema.sections?.map(s => ({
            name: s.name,
            label: tSec(s),
            description: s.description,
            columns: s.columns,
            // `?? []` — see the tabbed arm above (objectui#7051).
            fields: s.fields ?? [],
            // The collapse pair (objectui#9849 step two — director ruling
            // letter E, item 1: group semantics attach 「on every arm」). The
            // spec declares both on `sections[]`; this map used to copy
            // neither, so the modal silently ignored a declared collapse.
            collapsible: s.collapsible,
            collapsed: s.collapsed,
            // ADR-0089 section predicate (#6111) — key-by-key rebuild, so an
            // uncopied key is silently dropped before ModalForm ever sees it.
            visibleWhen: (s as any).visibleWhen,
            visibleWhenFault: s.visibleWhenFault,
            // `className` / `gridClassName`: deliberately not copied — see the
            // tabbed arm above (objectstack#13626, ruled 2026-09-01).
          })),
          open: schema.open,
          onOpenChange: schema.onOpenChange,
          modalSize: schema.modalSize,
          modalCloseButton: schema.modalCloseButton,
        }}
        dataSource={dataSource}
        className={schema.className}
      />
    );
  }

  // Default: simple form
  return <SimpleObjectForm schema={schema} dataSource={dataSource} />;
};

