/**
 * Auto-Layout for ObjectForm
 *
 * Provides intelligent, zero-configuration default layout for metadata-driven forms.
 * When the user has not explicitly set columns/colSpan/sections, this module
 * infers optimal layout based on field count and field types.
 *
 * Priority: User configuration > Auto-layout inference
 */

import type { FormField } from '@object-ui/types';
import { SERVER_OWNED_FIELD_NAMES } from './sanitize';

/** FormField types that are computed/aggregate and must be excluded from modal edit/create forms */
const AUTO_GENERATED_FORM_TYPES = new Set([
  'field:formula',
  'field:summary',
  'field:auto_number',
  'field:autonumber',
  // NOTE: 'field:master_detail' is NOT excluded here. From the child's perspective,
  // a master-detail field is the FK lookup to its parent and is typically required
  // (NOT NULL in the database). It must appear in create/edit forms as a lookup picker.
  // The "embedded sublist on parent detail page" use-case is rendered separately
  // via related-list views, not via the master-detail field type itself.
]);

/**
 * Field types that should span full width in multi-column layouts.
 *
 * Two spellings per type on purpose: the `field:` entries are the widget ids
 * `mapFieldTypeToFormType` produces (what a resolved `FormField.type` carries),
 * the BARE entries are `@objectstack/spec` `FieldType` names — app-shell's
 * `ObjectFormDesigner` passes a raw `objectDef.fields[x].type` straight in.
 * Both are matched RAW, so a bare member that is not a spec type name — and a
 * `field:` member that is not a registered widget id — silently matches
 * nothing.
 *
 * That is what `rich-text` / `field:rich-text` were: the spec spells the type
 * `richtext` (widget `field:richtext`) and REJECTS `rich-text`, which survives
 * only as a typo key in the spec's own `suggestFieldType` table. The set never
 * widened a rich-text field while `markdown` and `html` beside it did, and the
 * detail view's twin set had the identical hole — so the same field read wide
 * in neither surface (#4250). The dead spellings are dropped rather than kept
 * alongside: the alias table is the one place aliases belong.
 *
 * `grid` is NOT a spec `FieldType` — it is a sanctioned objectui-local key
 * (`GridFieldMetadata` in `@object-ui/types`), which is why it is exempt from
 * the spec-name pin in the tests.
 */
const WIDE_FIELD_TYPES = new Set([
  'field:textarea',
  'field:markdown',
  'field:html',
  'field:grid',
  'field:richtext',
  'textarea',
  'markdown',
  'html',
  'grid',
  'richtext',
]);

/**
 * Object field types that are auto-generated/aggregate and should be excluded
 * from modal edit/create forms — they are either computed server-side or render
 * as full-page sub-tables that belong on detail views, not dialogs.
 *
 * NOTE: master_detail/masterDetail are NOT excluded here. From the child-side
 * the field is the FK lookup to the parent (often required / NOT NULL); it must
 * appear in create/edit forms as a lookup picker. The "embedded sublist on the
 * parent's detail page" pattern is rendered by related-list views, not by this
 * field type.
 */
const AUTO_GENERATED_FIELD_TYPES = new Set([
  'formula',
  'summary',
  'auto_number',
  'autonumber',
]);

/**
 * Check if a field type is "wide" (should span full row in multi-column layout).
 */
export function isWideFieldType(type: string): boolean {
  return WIDE_FIELD_TYPES.has(type);
}

/**
 * Check if an object field type is auto-generated (formula, summary, auto_number).
 */
export function isAutoGeneratedFieldType(type: string): boolean {
  return AUTO_GENERATED_FIELD_TYPES.has(type);
}

/**
 * Infer the MAX column count from the field count (objectstack-ai/objectstack#2578). This is an UPPER
 * BOUND — the actual column count at render time is decided by the CSS
 * container queries in {@link CONTAINER_GRID_COLS} against the form's REAL
 * width, so a narrow drawer stays 1–2 columns while the SAME form on a wide
 * page spreads out to this cap. The cap scales with field count so a light
 * form is never thinned across too many columns, while a field-heavy record
 * can use the full width.
 *
 * Rules (upper bound; container queries clamp to the actual width):
 * - 0–3 fields  → 1 column
 * - 4–8 fields  → 2 columns
 * - 9–15 fields → 3 columns
 * - 16+ fields  → 4 columns
 */
export function inferColumns(fieldCount: number): number {
  if (fieldCount <= 3) return 1;
  if (fieldCount <= 8) return 2;
  if (fieldCount <= 15) return 3;
  return 4;
}

/** Clamp a raw column-ish number into 1..4 (the grid keys we support). */
function clampGrid(n: number | undefined): number {
  return n && n > 0 ? Math.min(Math.floor(n), 4) : 1;
}

/**
 * Resolve the effective colSpan (grid cells) a field occupies, given the form's
 * grid width and the section's desired column count (objectstack-ai/objectstack#2578).
 *
 * The column count is derived per surface (mobile 1 / modal 2 / page 3-4), so
 * the robust field-width primitive is the relative `span`, NOT an absolute
 * colSpan. Precedence:
 *   1. `span: 'full'`     → whole row (grid cells).
 *
 * ⚠️ «Whole row» is a claim about what RENDERS, and this function only returns
 * a number. It is kept by the form renderer's `spanLadderFor`, which turns
 * that number into one col-span class per container-query tier. Until
 * `bd0995738` the renderer emitted a single class for the widest tier only,
 * so this sentence was true of the return value and false on screen at every
 * intermediate width. ⛔ A pin under this function cannot observe that — see
 * `__tests__/spanFullTierLadder-9244.test.tsx` for the leg that can.
 *
 *   2. legacy `colSpan`   → honoured but CLAMPED to the grid (never overflows).
 *   3. wide widget type   → whole row (textarea/markdown/… — the `span:'auto'` default).
 *   4. section density    → grid / sectionColumns, so `sectionColumns` fields fill a row.
 *
 * `sectionColumns` defaults to the grid width, i.e. one field per cell (the flat
 * form's historical behaviour) when there is no narrower section.
 */
export function resolveColSpan(
  field: FormField,
  gridColumns: number,
  sectionColumns?: number,
): number {
  const grid = clampGrid(gridColumns);
  if (grid <= 1) return 1;

  const span = (field as { span?: 'auto' | 'full' }).span;
  if (span === 'full') return grid;

  // Legacy absolute colSpan — honoured but clamped so it can never overflow the
  // current grid (the fragility `span` exists to replace).
  if (field.colSpan != null) {
    return Math.min(Math.max(1, Math.floor(field.colSpan)), grid);
  }

  // `span: 'auto'` (or unset): wide widgets take the whole row.
  if (field.type && isWideFieldType(field.type)) return grid;

  // Otherwise fill the section's density: N per row → grid/N cells each.
  const secCols = Math.min(Math.max(1, Math.floor(sectionColumns || grid)), grid);
  return Math.min(grid, Math.max(1, Math.round(grid / secCols)));
}

/**
 * Apply the resolved colSpan to each field so the form's CSS grid lays them out
 * at the intended density. Span-aware and clamping (objectstack-ai/objectstack#2578); wide fields still
 * span the full row (the `span: 'auto'` default). `section-divider` rows are
 * left untouched (they carry their own full-row span).
 *
 * @param gridColumns    The form's grid column count (1-4).
 * @param sectionColumns The desired columns for THIS group of fields (defaults
 *                       to the grid width = one field per cell).
 * @returns A new array of fields with colSpan applied where needed.
 */
export function applyAutoColSpan(
  fields: FormField[],
  gridColumns: number,
  sectionColumns?: number,
): FormField[] {
  const grid = clampGrid(gridColumns);
  if (grid <= 1) return fields;

  return fields.map(field => {
    if ((field as { type?: string }).type === 'section-divider') return field;
    const eff = resolveColSpan(field, grid, sectionColumns);
    if (eff > 1) return { ...field, colSpan: eff };
    // eff === 1: strip any stale larger colSpan so it doesn't overflow a
    // narrower grid than the author imagined.
    if (field.colSpan != null && field.colSpan !== 1) return { ...field, colSpan: 1 };
    return field;
  });
}

/**
 * System field names that are always auto-managed by the platform and should
 * never appear on create/edit forms regardless of how they are declared on the
 * schema.
 *
 * ⭐ This is the SAME object the write path refuses — `SERVER_OWNED_FIELD_NAMES`
 * in `sanitize.ts`, whose header carries the roster's full rationale. It used
 * to be a second hand-written copy here, and the copies drifted: this one had
 * dropped `owner_id` from the rendered form while the write-side copy still
 * emitted it, so an edit form showed the user business inputs and sent back the
 * ownership column anyway (objectui#10108). One object, one invariant — a form
 * never writes a field it refuses to render.
 */
const SYSTEM_FIELD_NAMES = SERVER_OWNED_FIELD_NAMES;

/**
 * Filter out auto-managed system fields (id, audit timestamps, tenant/owner ids).
 * Applied in BOTH create and edit modes, because these fields are always
 * server-populated and rendering them as inputs (even when disabled) just
 * clutters the form. The detail page surfaces the audit metadata via
 * `RecordMetaFooter`.
 */
export function filterSystemFields(
  fields: FormField[],
  objectSchema?: any,
): FormField[] {
  return fields.filter((field) => {
    if (SYSTEM_FIELD_NAMES.has(field.name)) return false;
    const objField = objectSchema?.fields?.[field.name];
    // Honor `hidden: true` — internal/system fields (e.g. database_url,
    // metadata JSON blobs) must never surface as editable inputs in an
    // auto-generated form. The list grid (ObjectGrid) and detail drawer
    // already drop hidden fields; the auto-form is the one place that did
    // not, which leaked e.g. sys_environment.metadata as a raw JSON
    // textarea into the edit dialog. Applied in create AND edit.
    if (objField?.hidden === true) return false;
    // Also drop fields the schema explicitly marks readonly — these are
    // platform-managed (e.g. id alias, formula result columns).
    if (objField?.readonly === true) return false;
    return true;
  });
}

/**
 * Filter out auto-generated/readonly fields for create/edit mode.
 *
 * Dropped:
 * - `formula`, `summary`, `autonumber`, `master_detail` field types (server-computed).
 * - Fields with `readonly: true` on the object schema (e.g. `id`, `created_at`).
 * - Well-known system field names (id, created_at/createdAt, updated_at/updatedAt, etc.),
 *   even when the schema omits `readonly` — these are always platform-managed.
 *
 * Callers can force a readonly field back into the form by marking it
 * `hidden: false, readonly: false` in FormField overrides.
 *
 * @param fields - The form fields array
 * @param objectSchema - The object schema with original field metadata
 * @returns Filtered fields array
 */
export function filterCreateModeFields(
  fields: FormField[],
  objectSchema?: any
): FormField[] {

  return fields.filter(field => {
    // Drop well-known system-managed fields by name (id, created_at, updated_at, …).
    if (SYSTEM_FIELD_NAMES.has(field.name)) return false;

    // Check FormField.type directly (mapped type like 'field:formula')
    if (field.type && AUTO_GENERATED_FORM_TYPES.has(field.type)) return false;

    // Check against object schema field type + readonly flag
    if (!objectSchema?.fields) return true;
    const objField = objectSchema.fields[field.name];
    if (!objField) return true; // keep fields not in schema (custom fields)

    // Drop fields the schema declares as readonly — they are auto-managed.
    if (objField.readonly === true) return false;

    return !isAutoGeneratedFieldType(objField.type);
  });
}

/**
 * Filter auto-generated computed fields (formula, summary, etc.) — applied in
 * CREATE mode only. In edit mode these fields remain visible so users can see
 * their current computed values rendered as readonly.
 */
export function filterAutoGeneratedFields(
  fields: FormField[],
  objectSchema?: any,
): FormField[] {
  return fields.filter((field) => {
    if (field.type && AUTO_GENERATED_FORM_TYPES.has(field.type)) return false;
    const objField = objectSchema?.fields?.[field.name];
    if (!objField) return true;
    return !isAutoGeneratedFieldType(objField.type);
  });
}

/**
 * Container-query-based grid classes for laying out form FIELDS inside a
 * section. Uses `@container` / `@md:` / `@2xl:` / `@4xl:` variants so the grid
 * responds to the form's actual width (modal / drawer / split panel) instead of
 * the viewport — a narrow modal stays single-column regardless of viewport size.
 *
 * `1` maps to `undefined` so the caller falls back to the form renderer's
 * default single-column stack (`space-y-4`).
 */
export const CONTAINER_GRID_COLS: Record<number, string | undefined> = {
  1: undefined,
  2: 'grid gap-4 grid-cols-1 @md:grid-cols-2',
  3: 'grid gap-4 grid-cols-1 @md:grid-cols-2 @2xl:grid-cols-3',
  4: 'grid gap-4 grid-cols-1 @md:grid-cols-2 @2xl:grid-cols-3 @4xl:grid-cols-4',
};

/** Clamp an arbitrary column count into the 1–4 keys of {@link CONTAINER_GRID_COLS}. */
export function containerGridColsFor(columns: number | undefined): string | undefined {
  const cols = columns && columns > 0 ? Math.min(Math.floor(columns), 4) : 1;
  return CONTAINER_GRID_COLS[cols];
}

/**
 * The field grid of a sectioned form whose sections do not all fit one grid
 * (objectui#12548): one column below `@md`, twelve tracks from `@md` up.
 *
 * Twelve is the least count every authored section density divides
 * (`@objectstack/spec` `FormSectionSchema.columns` is `1 | 2 | 3 | 4`), so in
 * this grid a field's colSpan is in TWELFTHS of the row: 12 / 6 / 4 / 3 for a
 * 1 / 2 / 3 / 4-column section. The form renderer draws a twelfths colSpan as
 * one class per tier, keeping each density's step ladder from
 * {@link CONTAINER_GRID_COLS} (at most two per row at `@md`, three at `@2xl`,
 * four at `@4xl`); its table is `TWELVE_TRACK_SPAN_CLASS` in
 * `@object-ui/components`' form renderer.
 *
 * ⛔ A literal, never assembled: Tailwind's scanner reads source text.
 */
export const TWELVE_TRACK_GRID_COLS = 'grid gap-4 grid-cols-1 @md:grid-cols-12';

/**
 * How many fields per row a section draws where neither it nor its form
 * declares `columns` (objectui#12592): two from the container's `@md` tier up,
 * one below it, so a phone keeps its single column.
 *
 * An undeclared density is the renderer's choice by available width, and a
 * declared one — `1` included — is drawn as written (the section-`columns`
 * fork on objectui#12521, ruled 6204264665; `@objectstack/spec` dropped
 * `FormSectionSchema.columns`' `default(1)` in objectstack-ai/objectstack#23740,
 * so an undeclared section reaches every host). The container query makes
 * "available width" literal: the same section draws one per row in a narrow
 * drawer or on a phone, and two in a dialog or a page.
 */
export const UNDECLARED_SECTION_COLUMNS = 2;

/** An authored column count clamped into the 1–4 grid keys; anything else reads as not declared. */
function declaredColumns(n: unknown): number | undefined {
  return typeof n === 'number' && n > 0 ? Math.min(Math.floor(n), 4) : undefined;
}

/**
 * One section's fields per row: its declared `columns` as written, else the
 * form's declared `columns` (what an undeclared section always filled), else
 * {@link UNDECLARED_SECTION_COLUMNS}.
 */
export function sectionColumnsFor(sectionColumns: unknown, formColumns: unknown): number {
  return declaredColumns(sectionColumns) ?? declaredColumns(formColumns) ?? UNDECLARED_SECTION_COLUMNS;
}

/**
 * The ONE grid width of a sectioned form: the form's declared `columns`, else
 * the widest section's {@link sectionColumnsFor}.
 *
 * @param formColumns    The form's DECLARED `columns` (`undefined` when none).
 * @param sectionColumns The DECLARED `columns` of every section the form draws.
 */
export function sectionedFormColumns(
  formColumns: unknown,
  sectionColumns: ReadonlyArray<unknown>,
): 1 | 2 | 3 | 4 {
  const widest = sectionColumns.length
    ? Math.max(...sectionColumns.map((c) => sectionColumnsFor(c, formColumns)))
    : UNDECLARED_SECTION_COLUMNS;
  return (declaredColumns(formColumns) ?? widest) as 1 | 2 | 3 | 4;
}

/** The field grid a sectioned host draws, and how it lays out one section's fields on it. */
export interface SectionedGridLayout {
  /** The form's grid width in the 1–4 vocabulary (`FormSchema.columns`). */
  columns: 1 | 2 | 3 | 4;
  /** The field container's grid classes; `undefined` for a one-column form. */
  fieldContainerClass: string | undefined;
  /** Lay one section's fields out at that section's DECLARED `columns` (`undefined` when none). */
  layOut: (fields: FormField[], sectionColumns?: unknown) => FormField[];
}

/**
 * The ONE layout rule of a sectioned form — `ModalForm`, `ObjectForm`,
 * `SplitForm`, `TabbedForm` and `WizardForm` all call it (objectui#12548).
 *
 * Every section shares the form's single field grid (one form, one
 * react-hook-form instance — #2153/#2959), and every authored section must
 * still draw its OWN `columns` count per row: `FormSectionSchema.columns` is a
 * per-section count, whatever the other sections declare.
 *
 * - When every section's count is 1 or the grid's own width, the grid is
 *   {@link CONTAINER_GRID_COLS}' and the spans are {@link applyAutoColSpan}'s,
 *   byte for byte what a single-density form always drew: on that grid a
 *   one-column section's fields take the row and a full-width section's take
 *   one cell each, which is exactly their count.
 * - Otherwise a section's count does not fit that grid at some tier — a
 *   `columns: 2` section on a 3-wide grid spanned 2 of 3 cells, ONE field per
 *   row, and a `columns: 3` section on a 4-wide grid spanned 1 cell, FOUR per
 *   row (`Math.round(grid / sectionColumns)`). The grid becomes
 *   {@link TWELVE_TRACK_GRID_COLS} and each field spans twelfths of the row:
 *     1. `span: 'full'`, or a wide widget type → 12, the whole row;
 *     2. an authored `colSpan` → that many of its SECTION's columns, clamped
 *        to them (it keeps winning over the density);
 *     3. otherwise → 12 / the section's columns.
 *
 * A section's count is clamped to the grid width, as it always was: the form
 * view's own `columns` outranks how a section fills it.
 *
 * Every host hands it what the AUTHOR wrote, never a count it resolved itself
 * (objectui#12592): an undeclared section and an undeclared form resolve here,
 * through {@link sectionColumnsFor} and {@link sectionedFormColumns}, so a
 * section that declares nothing draws {@link UNDECLARED_SECTION_COLUMNS} per
 * row in the dialog and on every page host alike.
 *
 * @param formColumns    The form's DECLARED `columns` (`undefined` when none).
 * @param sectionColumns The DECLARED `columns` of every section the form draws.
 */
export function sectionedGridLayout(
  formColumns: unknown,
  sectionColumns: ReadonlyArray<unknown>,
): SectionedGridLayout {
  const grid = sectionedFormColumns(formColumns, sectionColumns);
  const density = (declared: unknown) =>
    Math.min(sectionColumnsFor(declared, formColumns), grid);
  const fits = sectionColumns.every((c) => {
    const d = density(c);
    return d === 1 || d === grid;
  });

  if (fits) {
    return {
      columns: grid,
      fieldContainerClass: containerGridColsFor(grid),
      layOut: (fields, declared) =>
        grid > 1 ? applyAutoColSpan(fields, grid, density(declared)) : fields,
    };
  }

  return {
    columns: grid,
    fieldContainerClass: TWELVE_TRACK_GRID_COLS,
    layOut: (fields, declared) => {
      const d = density(declared);
      return fields.map((field) => {
        if ((field as { type?: string }).type === 'section-divider') return field;
        return { ...field, colSpan: twelfthsFor(field, d) };
      });
    },
  };
}

/** The twelfths of a row one field spans in a `sectionColumns`-wide section. */
function twelfthsFor(field: FormField, sectionColumns: number): number {
  const span = (field as { span?: 'auto' | 'full' }).span;
  if (span === 'full') return 12;
  if (field.colSpan != null) {
    const cells = Math.min(Math.max(1, Math.floor(field.colSpan)), sectionColumns);
    return (12 * cells) / sectionColumns;
  }
  if (field.type && isWideFieldType(field.type)) return 12;
  return 12 / sectionColumns;
}

/**
 * Build the layout-related props for a *section's* inner form (`SchemaRenderer`).
 *
 * A section groups its fields and lays them out in `columns` columns. That grid
 * must be applied to the FIELD container INSIDE the form — not wrapped around
 * the whole form element. Wrapping the single `<form>` in a multi-column grid
 * (as the section variants used to) puts the entire form in the first grid cell
 * and leaves every other column permanently empty. Here we instead thread
 * `columns` + `fieldContainerClass` into the form so its own field container
 * becomes the multi-column grid — mirroring the flat-fields layout path.
 *
 * @param fields  Already-built (and permission-filtered) section fields.
 * @param columns Section column count (1–4).
 */
export function sectionFormLayout(
  fields: FormField[],
  columns: number | undefined,
): { fields: FormField[]; columns: number; fieldContainerClass?: string } {
  const cols = columns && columns > 1 ? Math.min(Math.floor(columns), 4) : 1;
  const laidOut = cols > 1 ? applyAutoColSpan(fields, cols) : fields;
  const fieldContainerClass = containerGridColsFor(cols);
  return {
    fields: laidOut,
    columns: cols,
    ...(fieldContainerClass ? { fieldContainerClass } : {}),
  };
}

/**
 * Infer the modal size for a dialog whose author declared none, from the
 * number of layout columns it will show.
 *
 * Mapping:
 * - 0–1 column → 'lg' (max-w-2xl)
 * - 2+ columns → 'xl' (max-w-5xl)
 *
 * ⛔ Never 'full' (objectui#12521): a derived dialog is bounded, and its width
 * follows its content (the objectui#12080 ruling). 'full' (95vw) stays
 * available to an author who declares `modalSize: 'full'`. The bound changes
 * no grid class an authored layout carries: the field grid's tiers are
 * container queries, so an authored section draws as many of its columns as
 * the bounded dialog's width admits.
 */
export function inferModalSize(columns: number): 'sm' | 'default' | 'lg' | 'xl' | 'full' {
  if (columns <= 1) return 'lg';
  return 'xl';
}

/**
 * Main auto-layout orchestrator.
 * Applies intelligent defaults only when the user has not explicitly configured layout.
 *
 * @param formFields - Generated form fields
 * @param objectSchema - The original object schema (with field types)
 * @param schemaColumns - User-provided columns (from ObjectFormSchema)
 * @param mode - Form mode ('create' | 'edit' | 'view')
 * @returns Object with processed fields and inferred columns
 */
export function applyAutoLayout(
  formFields: FormField[],
  objectSchema: any,
  schemaColumns: number | undefined,
  mode: string | undefined
): { fields: FormField[]; columns: number | undefined } {
  let fields = [...formFields];

  // Step 1a: Always drop platform-managed system fields (id, audit timestamps,
  // tenant ids, etc.) from create AND edit forms. They're populated by the
  // driver/security plugin, and the detail page surfaces audit metadata via
  // RecordMetaFooter — so showing them as (disabled) inputs is pure clutter.
  fields = filterSystemFields(fields, objectSchema);

  // Step 1b: In create mode, additionally drop formula/summary/auto-number
  // fields (server-computed). In edit mode keep them so users can see their
  // current computed values, typically rendered as readonly.
  if (mode === 'create') {
    fields = filterAutoGeneratedFields(fields, objectSchema);
  }

  // Step 2: If user explicitly set columns, respect it but still apply auto colSpan
  if (schemaColumns !== undefined) {
    fields = applyAutoColSpan(fields, schemaColumns);
    return { fields, columns: schemaColumns };
  }

  // Step 3: Infer columns from field count
  const columns = inferColumns(fields.length);

  // Step 4: Apply auto colSpan for wide fields
  fields = applyAutoColSpan(fields, columns);

  return { fields, columns };
}
