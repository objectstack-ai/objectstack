export interface ModalFormSectionConfig {
  name?: string;
  label?: string;
  description?: string;
  columns?: 1 | 2 | 3 | 4;
  /**
   * The same three entry shapes as `ObjectFormSection.fields`, by reference:
   * a field name, the form view's `{ field, … }` entry, or an inline
   * `FormField` (objectui#11615).
   */
  fields: NonNullable<ObjectFormSection['fields']>;
  /**
   * Whether the section can be collapsed — spec `FormSection.collapsible`.
   * `collapsed: true` implies it (objectui#9780). The control lives on the
   * section's divider row, so a section with neither `label` nor
   * `description` cannot carry one: it renders open and is reported
   * (objectui#9849, director ruling letter E). Stacked layout only — the
   * `tabbed` content layout draws tabs, which do not collapse.
   */
  collapsible?: boolean;
  /** Whether the section starts collapsed — spec `FormSection.collapsed`. Same rules as `collapsible`. */
  collapsed?: boolean;
  /**
   * ADR-0089 `FormSection.visibleWhen` — conditional visibility for the
   * section's divider HEADER, evaluated by the form renderer with the canonical
   * engine and the host predicate scope (#6010/#6111). Fails OPEN.
   */
  visibleWhen?: string | { dialect?: string; source: string };
  /**
   * The fault direction of {@link visibleWhen}, by reference to
   * `ObjectFormSection.visibleWhenFault` (objectui#13055): `'hidden'` (a field
   * group's predicate) hides the section when it cannot be evaluated.
   */
  visibleWhenFault?: ObjectFormSection['visibleWhenFault'];
  /** Custom CSS class for the section's header row (stacked layout). */
  className?: string;
  /**
   * Custom CSS class for the section's field grid. Applied to the section's tab
   * panel in the `tabbed` layout; in the stacked layout every section shares one
   * grid inside the single form (#2959), so there is none to override.
   */
  gridClassName?: string;
}

export interface ModalFormSchema {
  type: 'object-form';
  formType: 'modal';
  objectName: string;
  mode: 'create' | 'edit' | 'view';
  /** Record ID (for edit/view modes). A string, per the one record-id rule on `DataSource` (objectui#9511) — `ObjectForm` builds this schema from the authorable `ObjectFormSchema.recordId`, which is a string, and `findOne` takes a string. */
  recordId?: string;
  title?: string;
  description?: string;
  sections?: ModalFormSectionConfig[];
  /** Internal content layout (ADR-0050, objectstack-ai/objectstack#1890): 'tabbed' renders sections as
   *  tabs inside the modal, so "modal + tabbed" composes. Default stacks them. */
  contentLayout?: 'simple' | 'tabbed';
  fields?: string[];
  customFields?: FormField[];

  /**
   * Whether the modal is open.
   * @default true
   */
  open?: boolean;

  /**
   * Callback when open state changes.
   */
  onOpenChange?: (open: boolean) => void;

  /**
   * Modal dialog size.
   * @default 'default'
   */
  modalSize?: 'sm' | 'default' | 'lg' | 'xl' | 'full';

  /**
   * Whether the dialog draws its close (X) button. Only an explicit `false`
   * hides it (objectui#11061); both dialog arms (the flat form and the
   * `subforms` master-detail form) pass it to `MobileDialogContent`'s
   * `showCloseButton`. Hidden, the form is still dismissable: Escape (and a
   * backdrop click) still reach `onOpenChange(false)`, as does the Cancel
   * action when it is shown.
   * @default true
   */
  modalCloseButton?: boolean;

  /**
   * Guard against *accidentally* discarding unsaved input. When the form has
   * unsaved changes, an accidental close (backdrop click, Escape, or the X
   * button) first asks the user to confirm. The explicit Cancel button is an
   * intentional discard and always closes immediately. Set to `false` to drop
   * the confirmation entirely.
   * @default true
   */
  confirmOnDiscard?: boolean;

  // Common form props
  showSubmit?: boolean;
  submitText?: string;
  showCancel?: boolean;
  cancelText?: string;
  initialValues?: Record<string, any>;
  initialData?: Record<string, any>;
  readOnly?: boolean;
  layout?: 'vertical' | 'horizontal';
  columns?: number;
  /**
   * Override persistence — the seam a host uses to own the write. Declared as
   * `ObjectFormSchema['submitHandler']` rather than restated, so this variant
   * and the canonical key `ObjectForm` forwards can never drift apart.
   * When supplied, the form validates and hands the collected values
   * to this handler INSTEAD of calling `dataSource.create` /
   * `dataSource.update`; the returned record is passed on to `onSuccess`.
   * In `edit` mode, for a record this form read itself, it hands over what it
   * would have written: the fields that differ from that read, or the full
   * sanitized payload when nothing changed (objectui#10156; the whole rule is
   * on `ObjectFormSchema['submitHandler']`).
   *
   * `MasterDetailForm` supplies it to route the parent AND its child
   * collections through one atomic `batchTransaction` (#2679 / ADR-0034
   * item 4). A renderer that does not read it writes the parent on its own and
   * escapes that transaction — objectui#6176.
   */
  submitHandler?: ObjectFormSchema['submitHandler'];

  onSuccess?: (data: any) => void | Promise<void>;
  onError?: (error: Error) => void;
  onCancel?: () => void;
  className?: string;
  /** Inline child collections — renders the modal as an atomic master-detail
   *  form. Each entry needs only `childObject` (FK + columns derived). */
  subforms?: Array<{
    childObject: string;
    relationshipField?: string;
    columns?: any[];
    amountField?: string;
    totalField?: string;
    title?: string;
    addLabel?: string;
    minRows?: number;
    maxRows?: number;
  }>;
}

export interface ModalFormProps {
  schema: ModalFormSchema;
  dataSource?: DataSource;
  className?: string;
}

/**
 * Size class map for the dialog content.
 *
 * Uses `sm:` prefix so that `tailwind-merge` correctly resolves the conflict
 * with MobileDialogContent's base `sm:max-w-lg` class.  On mobile (< sm) the
 * dialog is already full-screen, so max-width only matters at sm+ breakpoints.
 *
 * The bounded wide sizes, `lg` and `xl`, also read the shared
 * {@link DIALOG_VIEWPORT_GUTTER} (objectui#12593, promoted to one export by
 * objectui#12603): 1rem from the window edge at every width from `sm` up.
 * `sm` (384px) and `default` (512px) never reach the edge at or above 640px,
 * and `full` keeps its own `95vw`, so none of the three reads it.
 */
const modalSizeClasses: Record<string, string> = {
  sm: 'sm:max-w-sm',
  default: 'sm:max-w-lg',
  lg: `sm:max-w-2xl ${DIALOG_VIEWPORT_GUTTER}`,
  xl: `sm:max-w-5xl ${DIALOG_VIEWPORT_GUTTER}`,
  full: 'sm:max-w-[95vw] sm:w-full',
};

/**
 * How many fields per row the dialog draws where the author declared no
 * `columns` (objectui#12521): two from the container's `@md` tier up, one
 * below it, so the phone sheet keeps its single column. It rides the spec's
 * own `columns` / `colSpan` path, so every field takes one cell — fields of
 * one kind share one width — while a wide kind (`isWideFieldType`: textarea,
 * rich text, markdown, html, an inline `grid`) and a `span: 'full'` field take
 * the whole row. Line items never reach this grid: they arrive as `subforms`,
 * which the master-detail arm below lays out across the dialog.
 *
 * It applies to a flat form with no `columns`. A SECTION that declares no
 * `columns` — the object's `fieldGroups` among them — gets the same count
 * through the one sectioned-form rule, `sectionedGridLayout`
 * (`UNDECLARED_SECTION_COLUMNS`), which every page host shares
 * (objectui#12592): an undeclared section density is the renderer's choice,
 * and a declared one — `1` included — is drawn as written (the
 * section-`columns` fork on objectui#12521, ruled 6204264665).
 *
 * The flat default is dialog-only on purpose: a flat page form, a drawer and
 * the detail view keep `inferColumns`, which they mirror between them.
 */
const DIALOG_DEFAULT_COLUMNS = UNDECLARED_SECTION_COLUMNS;

/** Clamp an authored column count into the 1–4 grid keys; anything else reads as not authored. */
const clampColumns = (n: unknown): number | undefined =>
  typeof n === 'number' && n > 0 ? Math.min(Math.floor(n), 4) : undefined;

export const ModalForm: React.FC<ModalFormProps> = ({
  schema,
  dataSource,
  className,
}) => {
  const { fieldLabel, sectionLabel } = useSafeFieldLabel();
  const { t } = useDiscardTranslation();
  // Upload-in-flight gate (objectui#10166): Save is refused, disabled and
  // EXPLAINED while a file/image widget below is still uploading.
  const uploadGate = useUploadGate();
  const previewMode = usePreviewMode();
  const perms = usePermissions();
  const [objectSchema, setObjectSchema] = useState<any>(null);
  // The ONE field-gate step every layout draws through (`gateFormFields`,
  // objectui#10612): FLS drops non-readable fields and disables non-editable
  // ones (`80c54122e`; fail-open when no PermissionProvider is mounted), and
  // the ADR-0092 D4 managed-object lock disables every field when the object's
  // affordance for the mode is closed — before objectui#10612 a managed object
  // drew live inputs here.
  const gateFields = useCallback(
    (fields: FormField[]): FormField[] =>
      gateFormFields(fields, {
        perms,
        objectName: schema.objectName,
        mode: schema.mode,
        objectSchema,
      }) as FormField[],
    [perms, schema.objectName, schema.mode, objectSchema],
  );
  const [formFields, setFormFields] = useState<FormField[]>([]);
  const [formData, setFormData] = useState<Record<string, any>>({});
  const [loading, setLoading] = useState(true);
  // objectui#10682 — the load error, kept per read (the object schema and the
  // record), each written only by the current run of its read and cleared when
  // a later run of that read commits: see `loadFailure.ts`. `error` is what
  // the error screen reports.
  const [loadFailures, setLoadFailures] = useState<LoadFailures>(NO_LOAD_FAILURES);
  const loadRunSeqRef = useRef<LoadRunSeq>({ schema: 0, record: 0 });
  const error = shownLoadFailure(loadFailures);
  const [isSubmitting, setIsSubmitting] = useState(false);
  // Unsaved-changes guard. `isDirty` is fed up from the inner form renderer via
  // onDirtyChange; `discardOpen` controls the confirm dialog shown when the user
  // tries to close a dirty form.
  const [isDirty, setIsDirty] = useState(false);
  const [discardOpen, setDiscardOpen] = useState(false);
  // Per-section LIVE collapse state, keyed like the divider rows. Unseeded on
  // purpose: an untoggled section falls back to its declared `collapsed`
  // inside `resolveSectionCollapse`, the one reader of that member — the same
  // shape as ObjectForm's grouped layout and DrawerForm (objectui#9849).
  const [collapsedSections, setCollapsedSections] = useState<Record<string, boolean>>({});
  // objectui#13246 — a section toggle is a TRANSITION. Opening a group draws
  // its field widgets, which are `React.lazy`, so the first time a type is
  // drawn the render suspends. As an ordinary update that suspension hid the
  // drawn body behind `ModalFormBodyPending` — the header the user had just
  // pressed included — and a browser drops focus from an element it stops
  // rendering, so the dialog's focus scope ended up holding it. As a
  // transition React keeps the drawn body on screen until the group's rows can
  // be drawn: the header keeps focus, and the next Tab reaches the group's
  // first field.
  const setSectionCollapsed = (key: string, next: boolean) =>
    startTransition(() => setCollapsedSections((prev) => ({ ...prev, [key]: next })));
  // OCC-guarded edit save + its conflict dialog (see occSave.tsx).
  const { saveWithOcc, conflictDialog } = useOccSave();
  // Whether the pending close came from the explicit Cancel button (so we fire
  // schema.onCancel) versus a backdrop/Escape/X dismissal (which historically
  // did not). Kept in a ref so it survives the confirm round-trip.
  const cancelIntentRef = useRef(false);
  const confirmOnDiscard = schema.confirmOnDiscard !== false;

  const isOpen = schema.open !== false;
  // `modalCloseButton` (objectui#11061): only an explicit `false` hides the
  // dialog's X; unset and `true` keep it.
  const showCloseButton = schema.modalCloseButton !== false;

  // Stable form id for linking the external submit button to the form element
  const formId = useId();

  // objectui#13130 — the dialog opens on its first editable field, not on its
  // Close button: the body loads after the content mounts, so Radix's own
  // first-tabbable pick found only Close. See `initialFieldFocus.ts`.
  const initialFieldFocus = useInitialFieldFocus();

  // `form.sections[].group` (objectui#11542): a section that points `group` at
  // one of the object's `fieldGroups` becomes the section that group declares,
  // through the ONE resolver `ObjectForm`'s `withGroups` uses, so no assembly
  // rule lives here. `ObjectForm` resolves above its routing fork, but the
  // console's record dialog and an action-opened modal mount THIS component
  // directly with the form view's sections as authored, so the dialog resolves
  // its own. Resolved once, above both content layouts (tabbed and stacked),
  // against the object schema this form already loads; while it loads the
  // form shows its skeleton. Returns `schema.sections` itself when no section
  // uses `group` — which includes every section list `ObjectForm` hands over,
  // already resolved — so no other modal takes a new path. Every resolved
  // member still goes through `gateFields` below, like an enumerated one.
  const resolvedSections = useMemo(
    () =>
      resolveSectionGroupReferences(schema.sections as ObjectFormSection[] | undefined, {
        objectName: schema.objectName,
        formType: schema.formType,
        objectDef: objectSchema,
        resolvable: typeof dataSource?.getObjectSchema === 'function',
      }) as ModalFormSectionConfig[] | undefined,
    [schema.sections, schema.objectName, schema.formType, objectSchema, dataSource],
  );

  // Field-group fallback (object-designer metadata): when the caller passes no
  // explicit sections, honor the object's declared `fieldGroups` the same way
  // ObjectForm's simple path does — one section per group, with flat-path
  // auto-layout parity (system/auto-generated fields filtered, the dialog's
  // default columns, wide fields spanning the row). An explicit curated
  // `sections` list from a form view always wins over this fallback.
  const derivedSections = useMemo(() => {
    // `customFields` does NOT switch the fallback off (objectui#10073): the
    // members are merged into `formFields` above, and ObjectForm derives its
    // groups over that same merged pool.
    if (schema.sections?.length) return null;
    let fs = filterSystemFields(formFields, objectSchema);
    if (schema.mode === 'create') fs = filterAutoGeneratedFields(fs, objectSchema);
    const sections = deriveFieldGroupSections(fs, (objectSchema as any)?.fieldGroups);
    if (!sections) return null;
    const columns = (clampColumns(schema.columns) ?? DIALOG_DEFAULT_COLUMNS) as 1 | 2 | 3 | 4;
    // A member's definition reaches a group's body through `buildSectionFields`,
    // the route an explicit section's takes (objectui#10254).
    return sections.map((s) => ({ ...s, columns })) as ModalFormSectionConfig[];
  }, [schema.sections, schema.columns, schema.mode, formFields, objectSchema]);

  const effectiveSections = resolvedSections?.length ? resolvedSections : (derivedSections ?? undefined);

  // Compute auto-layout for flat fields (no sections) to determine inferred columns
  // (`customFields` does not switch it off: the members are merged into
  // `formFields`, and ObjectForm auto-lays-out that merged list — objectui#10073.)
  // A form that declares no `columns` lays out at the dialog's default
  // (objectui#12521) through the same explicit-columns route an authored
  // `columns` takes, so `applyAutoLayout` never infers 3–4 columns here.
  const flatColumns = schema.columns ?? DIALOG_DEFAULT_COLUMNS;
  const autoLayoutResult = useMemo(() => {
    if (effectiveSections?.length) return null;
    return applyAutoLayout(formFields, objectSchema, flatColumns, schema.mode);
  }, [formFields, objectSchema, flatColumns, schema.mode, effectiveSections]);

  // The dialog's size when the author declared none (objectui#12521): bounded
  // — `lg` or `xl`, never `full` — and chosen from the grid that renders and
  // the field count, so a short form is not stretched across a wide dialog.
  // An authored `modalSize` (including `'full'`) is used as written.
  const effectiveModalSize = useMemo(() => {
    if (schema.modalSize) return schema.modalSize;
    const columns = effectiveSections?.length
      ? sectionedFormColumns(schema.columns, effectiveSections.map((s) => s.columns))
      : (autoLayoutResult?.columns ?? DIALOG_DEFAULT_COLUMNS);
    const fieldCount = effectiveSections?.length
      ? effectiveSections.reduce((n, s) => n + (Array.isArray(s.fields) ? s.fields.length : 0), 0)
      : (autoLayoutResult?.fields.length ?? 0);
    return inferModalSize(Math.min(columns, inferColumns(fieldCount)));
  }, [schema.modalSize, schema.columns, autoLayoutResult, effectiveSections]);

  const sizeClass = modalSizeClasses[effectiveModalSize] || modalSizeClasses.default;

  // Fetch object schema
  useEffect(() => {
    // objectui#10712 — a read an `objectName` or data-source change has
    // superseded commits nothing: not the schema, and not the `loading` release
    // the current read owns (the record read's `cancelled` below, applied here).
    let cancelled = false;
    // objectui#10682 — this run's writes to the schema read's failure; a newer
    // run of this effect makes them no-ops.
    const run = beginLoadRun(loadRunSeqRef, setLoadFailures, 'schema');
    const fetchSchema = async () => {
      if (!dataSource) {
        setLoading(false);
        return;
      }
      try {
        const data = await dataSource.getObjectSchema(schema.objectName);
        if (cancelled) return;
        setObjectSchema(data);
        run.commit();
      } catch (err) {
        if (cancelled) return;
        run.fail(err);
        setLoading(false);
      }
    };
    fetchSchema();
    return () => { cancelled = true; };
  }, [schema.objectName, dataSource]);

  // The record whose data `formData` currently holds. The fetch effect reads it
  // to tell a genuine record SWAP from a re-run of its own making —
  // `initialData`/`initialValues` are objects callers commonly rebuild every
  // render, and flashing the loading state for those would thrash.
  const loadedRecordIdRef = useRef<string | number | undefined>(undefined);
  // The record itself as read — the baseline an edit save diffs against, so
  // only the fields that changed are written (objectui#10156). Kept apart from
  // `formData`, which seeds the form and supplies the OCC token: advancing it
  // after a save would reseed the one and move the other. Set by the `findOne`
  // below and nowhere else, so a caller-supplied record is never a baseline.
  const loadedRecordRef = useRef<LoadedRecordSnapshot | null>(null);
  // objectui#10715 — the data-invalidation bus, read the way the default arm
  // reads it (the rule is stated once in `recordInvalidation.ts`): a change to
  // this record, to its object or to `'*'` re-reads the record IN PLACE through
  // the effect below while the form is pristine, and is held while it is dirty.
  // `isDirty` stays this modal's close guard; the bus hears the same channel.
  const { refetch: recordRefetch, onDirtyChange: onBusDirtyChange, saved: recordSaved } =
    useRecordInvalidation(schema.objectName, schema.recordId, !!schema.recordId && schema.mode !== 'create');
  const handleDirtyChange = useCallback((dirty: boolean) => {
    setIsDirty(dirty);
    onBusDirtyChange(dirty);
  }, [onBusDirtyChange]);

  // Fetch initial data
  useEffect(() => {
    // A `recordId` change re-enters this effect with the form still MOUNTED on
    // the previous record, which needs handling on two fronts (pinned by
    // recordSwapLoading.test.tsx):
    //  - go back to the loading state, so record A's values are not left on
    //    screen AND EDITABLE while B is in flight, to be swapped underneath in
    //    place when it lands. Anything typed there read as A's on screen but
    //    would have been submitted against B.
    //  - ignore a response that is no longer the one being awaited, so two
    //    overlapping reads land in REQUEST order, not completion order.
    let cancelled = false;
    // objectui#10682 — this run's writes to the record read's failure; a newer
    // run of this effect makes them no-ops.
    const run = beginLoadRun(loadRunSeqRef, setLoadFailures, 'record');
    const fetchData = async () => {
      if (schema.mode === 'create' || !schema.recordId) {
        // Seeded from something other than a read: no baseline to diff against.
        loadedRecordRef.current = null;
        // No persisted record to show, so the object's declared static
        // `defaultValue`s are the form's opening values (#4047) — caller-
        // supplied initial values still win. See `schemaDefaults` for why
        // runtime defaults (`NOW()`, `current_user`, CEL envelopes) are left
        // to the server and why option-level `default` is not read here.
        setFormData(seedCreateValues(objectSchema, resolveInitialRecord(schema), { currentUserId: perms.userId }));
        // Not a read, so no earlier record read's failure describes the form.
        run.commit();
        setLoading(false);
        return;
      }

      if (!dataSource) {
        loadedRecordRef.current = null;
        setFormData(resolveInitialRecord(schema));
        // Not a read either.
        run.commit();
        setLoading(false);
        return;
      }

      // Only a change of RECORD hides the form. Hiding it UNMOUNTS the inner
      // renderer, which is the only thing that reports dirtiness — it cannot
      // emit a final `onDirtyChange(false)` on its way out, so clear the flag
      // here or the close/unload guards stay armed for input that belongs to a
      // record no longer on screen.
      if (loadedRecordIdRef.current !== schema.recordId) {
        setLoading(true);
        setIsDirty(false);
      }

      try {
        const data = await dataSource.findOne(schema.objectName, schema.recordId);
        if (cancelled) return;
        loadedRecordIdRef.current = schema.recordId;
        loadedRecordRef.current = snapshotLoadedRecord(schema, data);
        setFormData(data || {});
        // The record on screen is the one this run read, so an earlier record
        // read's failure no longer describes it. A schema failure stays: this
        // read says nothing about the object's fields.
        run.commit();
      } catch (err) {
        if (cancelled) return;
        run.fail(err);
      } finally {
        if (!cancelled) setLoading(false);
      }
    };

    // A bus re-read (objectui#10715, `recordRefetch` below) re-runs this
    // effect for the record already on screen: it lands IN PLACE, since the
    // loading branch above is keyed on a change of record, and a re-read a
    // later run has superseded commits nothing, as above.
    if (objectSchema || !dataSource) {
      fetchData();
    }
    return () => { cancelled = true; };
  }, [objectSchema, schema.mode, schema.recordId, schema.initialData, schema.initialValues, dataSource, schema.objectName, recordRefetch]);

  // Build form fields from section config
  const buildSectionFields = useCallback(
    (section: ModalFormSectionConfig): FormField[] =>
      buildSectionFieldsShared(section as any, {
        objectSchema,
        objectName: schema.objectName,
        readOnly: schema.readOnly,
        mode: schema.mode,
        // Feeds the "no persisted record" test that decides whether a runtime
        // `defaultValue` excuses a field from `required` (#4069).
        recordId: schema.recordId,
        fieldLabel,
        // A member naming a section's field is that field's definition, as it
        // is in ObjectForm's merged pool — for explicit and derived sections
        // alike (objectui#10254; the explicit path used to regenerate every
        // named field from the object schema and drop the member).
        customFields: schema.customFields,
      }),
    [objectSchema, schema.readOnly, schema.mode, schema.recordId, schema.objectName, schema.customFields, fieldLabel],
  );

  // Build fields from flat field list (when no sections)
  useEffect(() => {
    if (!objectSchema && dataSource) return;

    // Ending the loading state here is only this effect's call when no record
    // read is outstanding (objectui#10659, the gate objectui#10190 gave the
    // drawer). Ended unconditionally, it painted an editable form while the
    // first read was in flight, and the landing record discarded what had been
    // typed — see `isRecordReadOutstanding`.
    const recordReadOutstanding = isRecordReadOutstanding({
      mode: schema.mode,
      recordId: schema.recordId,
      dataSource,
      loadedRecordId: loadedRecordIdRef.current,
    });
    const endLoading = () => {
      if (!recordReadOutstanding) setLoading(false);
    };

    if (schema.sections?.length) {
      endLoading();
      return;
    }

    // `customFields` MERGES over the generated set, as it does on ObjectForm's
    // default arm (objectui#10073 — it used to REPLACE it here). With no
    // object metadata the members are the whole field source.
    if (!objectSchema && !schema.customFields?.length) return;

    // ONE builder, shared with DrawerForm (objectui#4755) — the ADR-0036 rules
    // and `group` this path carries now reach both containers from a single
    // mapping instead of a hand-copied second loop.
    setFormFields(
      buildFlatFields({
        fields: schema.fields as any,
        objectSchema,
        objectName: schema.objectName,
        readOnly: schema.readOnly,
        mode: schema.mode,
        recordId: schema.recordId,
        fieldLabel,
        customFields: schema.customFields,
      }),
    );
    endLoading();
  }, [objectSchema, schema.fields, schema.customFields, schema.sections, schema.readOnly, schema.mode, dataSource]);

  // Handle form submission
  const handleSubmit = useCallback(async (data: Record<string, any>) => {
    // An upload is still in flight (objectui#10166). Saving now writes the
    // record WITHOUT the attachment and reports success. The footer's Save is
    // disabled and labelled for this, so reaching here means a keyboard submit
    // — refuse it with the same sentence the notice shows.
    if (uploadGate.uploading) {
      toast.error(uploadGate.reason);
      return;
    }
    setIsSubmitting(true);
    try {
      // No submit TARGET: a declared `submitHandler` owns the write and needs no
      // adapter of its own (objectui#6176's seam), so only a form with NEITHER it
      // nor a `dataSource` is target-less. The one target-less form that is still
      // legitimate is the inline-fields collector, whose `onSuccess` IS the write.
      // This arm used to be `if (!dataSource)` alone: it confirmed EVERY
      // adapter-less submit, bypassing a declared host seam and persisting
      // nothing (objectui#6300). See `submitTarget.ts` for the whole rule.
      if (!dataSource && !schema.submitHandler && hasInlineFieldSource(schema)) {
        if (schema.onSuccess) {
          await schema.onSuccess(data);
        }
        // Close modal on success
        schema.onOpenChange?.(false);
        return data;
      }

      let result;
      // FLS defence-in-depth, inside the ONE outbound filter: react-hook-form
      // retains state for unmounted/disabled fields, so the gate above is not
      // enough on its own — but the verdict is the same resolver's, adapted by
      // `fieldWriteGate` rather than copied here (`80c54122e`).
      const canEdit = fieldWriteGate(perms, schema.objectName, schema.mode);
      const payload = sanitizeFormData(data, objectSchema, { canEdit });
      // Omit the fields the producer owns (#4069) — see
      // `omitServerResolvedDefaults` for why an empty key is not the same as
      // no key at insert time. Create only: on an edit form a cleared column is
      // a real removal. An EDIT writes only the fields that differ from the
      // record this form read (objectui#10156; `dirtyEditPayload` holds the
      // rule, and sends whatever it cannot settle) — the owner included when
      // the user changed it, which is why it is handed the values as well
      // (objectui#12205). Computed ONCE (after the FLS strip above) so every
      // persistence route below — the host-owned seam included — writes the
      // identical payload.
      //
      // A CREATE writes the owner only when the user picked one against the
      // values this form opened with — `formData`, which on a create is the
      // seed and nothing else (objectui#12359; `createOwnerPayload` holds the
      // rule). A seeded owner left alone is not a pick and is not sent; the
      // server judges a pick, and its refusal is this form's error below.
      const owner = { values: data, objectSchema, canEdit };
      const writePayload = schema.mode === 'create'
        ? omitServerResolvedDefaults(createOwnerPayload(payload, formData, owner), objectSchema)
        : dirtyEditPayload(payload, loadedRecordRef.current, schema, owner);

      if (schema.submitHandler) {
        // The host owns persistence (e.g. MasterDetailForm batching the parent
        // + its child collections into ONE atomic transaction). The form
        // validates and hands the values over; it does NOT create/update
        // itself. Same seam and same precedence as SimpleObjectForm — every
        // renderer `ObjectForm` routes to must check it FIRST, or a declared
        // host-owned write silently becomes an independent one (objectui#6176).
        result = await schema.submitHandler(writePayload);
      } else if (!dataSource) {
        // No route left: no host seam and no adapter. Refuse instead of reporting
        // success — the `catch` below hands this to `schema.onError` and rethrows.
        throw noSubmitTargetError();
      } else if (schema.mode === 'create') {
        result = await dataSource.create(schema.objectName, writePayload);
      } else if (schema.mode === 'edit' && schema.recordId) {
        // OCC-guarded: sends `ifMatch` from the record we read; a 409 asks the
        // user to keep editing (modal stays open, draft intact) or overwrite.
        const outcome = await saveWithOcc({
          dataSource,
          objectName: schema.objectName,
          recordId: schema.recordId,
          payload: writePayload,
          baseRecord: formData,
        });
        if (outcome.status === 'cancelled') return;
        result = outcome.result;
      }
      // The write landed: a save from this still-open modal diffs against the
      // record as it now stands, not as first read.
      loadedRecordRef.current = advanceLoadedRecord(loadedRecordRef.current, schema, writePayload);
      // objectui#10715 — and what the form shows is what the server holds: a
      // bus change held while it was dirty (its own write's echo included) is
      // replayed now rather than behind input that is no longer unsaved.
      recordSaved();
      if (schema.onSuccess) {
        await schema.onSuccess(result);
      }
      // Close modal on success
      schema.onOpenChange?.(false);
      return result;
    } catch (err) {
      if (schema.onError) {
        schema.onError(err as Error);
      }
      throw err;
    } finally {
      setIsSubmitting(false);
    }
  }, [schema, dataSource, objectSchema, perms, saveWithOcc, formData, uploadGate.uploading, uploadGate.reason, recordSaved]);

  // Actually close the modal, firing onCancel only when the close originated
  // from the explicit Cancel button.
  const finalizeClose = useCallback(() => {
    setDiscardOpen(false);
    if (cancelIntentRef.current) {
      cancelIntentRef.current = false;
      schema.onCancel?.();
    }
    schema.onOpenChange?.(false);
  }, [schema]);

  // Attempt to close. With unsaved changes, intercept and ask for confirmation
  // instead of discarding the user's input. `viaCancel` marks the Cancel button.
  const attemptClose = useCallback((viaCancel: boolean) => {
    cancelIntentRef.current = viaCancel;
    if (confirmOnDiscard && isDirty) {
      setDiscardOpen(true);
    } else {
      finalizeClose();
    }
  }, [confirmOnDiscard, isDirty, finalizeClose]);

  // Browser-native "leave site?" prompt on tab close / reload while the form
  // is dirty. The in-app guard above only covers Radix close paths (backdrop,
  // Escape, the X) — a refresh bypasses them all and the input is gone.
  useEffect(() => {
    if (!isOpen || !isDirty || !confirmOnDiscard) return;
    const handler = (e: BeforeUnloadEvent) => {
      e.preventDefault();
      // Required for Chrome to actually show the prompt.
      e.returnValue = '';
    };
    window.addEventListener('beforeunload', handler);
    return () => window.removeEventListener('beforeunload', handler);
  }, [isOpen, isDirty, confirmOnDiscard]);

  // The explicit Cancel button is an *intentional* discard, so it closes
  // immediately — no "Discard changes?" prompt. The unsaved-changes guard only
  // intercepts *accidental* closes (backdrop click, Escape, the X), which Radix
  // routes through onOpenChange below. (attemptClose stays for that path.)
  const handleCancel = useCallback(() => {
    cancelIntentRef.current = true;
    finalizeClose();
  }, [finalizeClose]);

  // `vertical | horizontal` on the declared face; the fold that mapped any
  // other value to `vertical` was retired with `inline` / `grid`
  // (objectui#11168 slice 3, objectui#7759 group C).
  const formLayout = schema.layout ?? 'vertical';

  // Build base form schema
  // Actions are hidden inside the form renderer — we render them in a sticky footer instead
  const showSubmit = schema.showSubmit !== false && schema.mode !== 'view';
  const showCancel = schema.showCancel !== false;
  const submitLabel = schema.submitText || (schema.mode === 'create' ? t('form.create') : t('form.update'));
  const cancelLabel = schema.cancelText || t('common.cancel');

  // Typed as the child `form` node it is (objectui#11354), and so is every node
  // `renderContent` builds from it: each is a `FormSchema` const before it
  // reaches `SchemaRenderer`. `SchemaRenderer`'s `schema` slot is `BaseSchema`,
  // so a literal written inline there was checked against `BaseSchema`, not
  // against the `FormSchema` the `form` renderer reads.
  const baseFormSchema: FormSchema = {
    type: 'form',
    objectName: schema.objectName,
    layout: formLayout,
    defaultValues: formData,
    // The persisted record, for `previous`-scoped field rules and the
    // read-only submit strip (objectui#3484). Edit mode only: `formData` is
    // the raw `findOne` read there, while in create mode it is authored
    // seed values and there is no prior row to speak of.
    previousValues: schema.mode === 'edit' && schema.recordId ? formData : undefined,
    submitLabel,
    cancelLabel,
    showSubmit,
    showCancel,
    onSubmit: handleSubmit,
    onCancel: handleCancel,
    onDirtyChange: handleDirtyChange, // Feed unsaved-changes state up to the close guard and the bus gate
    showActions: false, // Hide actions — rendered in sticky footer
    id: formId,        // Link external submit button via form attribute
  };

  const renderContent = () => {
    if (error) {
      return (
        <div className="p-4 border border-red-300 bg-red-50 rounded-md">
          <h3 className="text-red-800 font-semibold">{t('form.errorLoading')}</h3>
          <p className="text-red-600 text-sm mt-1">{error.message}</p>
        </div>
      );
    }

    if (loading) {
      return (
        <div className="space-y-4" data-testid="modal-form-skeleton">
          {[1, 2, 3].map((i) => (
            <div key={i} className="space-y-2">
              <Skeleton className="h-4 w-24" />
              <Skeleton className="h-10 w-full" />
            </div>
          ))}
        </div>
      );
    }

    // Explicit sections layout (curated form view) — ONE form for ALL sections.
    //
    // Every section's fields share a single SchemaRenderer, i.e. one
    // react-hook-form instance and one <form> element (#2153/#2959). Rendering a
    // form PER section broke the modal in two ways: the footer submit button,
    // associated by `form={formId}`, can only reach the FIRST form, so section
    // 2+ silently dropped everything the user typed; and in the tabbed variant
    // Radix unmounted the inactive panel, destroying that tab's form state
    // outright. Same single-form pattern as ObjectForm / DrawerForm.
    if (resolvedSections?.length) {
      const sections = resolvedSections;
      const sectionKey = (sec: ModalFormSectionConfig, i: number) => sec.name || sec.label || String(i);
      // Section headers go through the same i18n hook ObjectForm uses, so a
      // translated group label wins over the raw metadata label.
      const sectionTitle = (sec: ModalFormSectionConfig) =>
        sec.name ? sectionLabel(schema.objectName, sec.name, sec.label || sec.name) : sec.label;

      // The form is ONE grid. Its width is the explicit form `columns`, else the
      // widest section's count, an undeclared section counting two
      // (objectui#12521, #12592); each section then lays ITS fields out at its
      // own count within that grid via colSpan (objectstack-ai/objectstack#2578), exactly like the
      // full-page sectioned form — by the one sectioned-form rule, which
      // switches to a 12-track grid when the sections' counts do not all fit
      // the widest one (objectui#12548). It is handed the AUTHORED counts.
      const sectionGrid = sectionedGridLayout(schema.columns, sections.map((sec) => sec.columns));
      const formColumns = sectionGrid.columns;
      const containerFieldClass = sectionGrid.fieldContainerClass;

      // FLS first, so a section whose every field is non-readable drops out
      // entirely (header included) instead of leaving an empty group.
      const groups = sections
        .map((section, index) => {
          const body = gateFields(buildSectionFields(section));
          const key = sectionKey(section, index);
          const title = sectionTitle(section);
          return {
            key,
            title,
            description: section.description,
            // The collapse pair, through the ONE resolution (objectui#9849
            // step two — director ruling letter E, item 1: 「on every arm」).
            // Read by the stacked layout below only; tabs do not collapse, so
            // the tabbed layout never asks, and never reports.
            resolveCollapse: () =>
              resolveSectionCollapse(section, {
                live: collapsedSections[key],
                title,
                description: section.description,
                where: `ModalForm section '${key}' of object '${schema.objectName}'`,
                setCollapsed: (next) => setSectionCollapsed(key, next),
              }),
            // Key-by-key rebuild: an uncopied key never reaches the divider
            // synthesis below (#6111).
            visibleWhen: section.visibleWhen,
            visibleWhenFault: section.visibleWhenFault,
            className: section.className,
            gridClassName: section.gridClassName,
            fields: sectionGrid.layOut(body, section.columns),
          };
        })
        .filter((g) => g.fields.length > 0);

      const sharedFormSchema: FormSchema = {
        ...baseFormSchema,
        columns: formColumns,
        ...(containerFieldClass ? { fieldContainerClass: containerFieldClass } : {}),
      };

      // ADR-0050 (objectstack-ai/objectstack#1890): a modal can host a tabbed layout — sections render as
      // tabs (label on the trigger) instead of a vertical stack, so a modal
      // create/edit form composes with `tabbed`. The renderer owns the tab strip
      // and panels (`fieldTabs`) so all tabs stay mounted inside the one form.
      if (schema.contentLayout === 'tabbed' && groups.length > 1) {
        const tabbedFormSchema: FormSchema = {
          ...sharedFormSchema,
          fields: groups.flatMap((g) => g.fields),
          fieldTabs: groups.map((g, index) => ({
            key: g.key,
            label: g.title || `Section ${index + 1}`,
            description: g.description,
            fields: g.fields.map((f) => f.name),
            containerClass: g.gridClassName,
            // The tab's predicate slot (#6237) — the same authored
            // `FormSection.visibleWhen` the stacked arm copies onto its
            // divider; the renderer evaluates it and hides trigger, panel
            // and fields together under the ruled hidden-group semantics.
            visibleWhen: g.visibleWhen,
            visibleWhenFault: g.visibleWhenFault,
          })),
        };
        return <SchemaRenderer schema={tabbedFormSchema} />;
      }

      // Stacked sections: a virtual `section-divider` field carries each group's
      // header inline. (A per-section Card would need a per-section form, which
      // is the defect above; `section.gridClassName` therefore has no per-section
      // grid to override here.)
      const allFields: FormField[] = [];
      groups.forEach((g) => {
        const collapse = g.resolveCollapse();
        // The ONE path from a section configuration to its divider row, and
        // the ONE row rule (objectui#9849, director ruling letter E) —
        // `projectSectionDivider` owns every key this row carries, including
        // the ADR-0089 predicate, the objectui#6236 membership claim and the
        // collapse pair, so this arm can no longer answer differently from
        // its siblings.
        allFields.push(
          ...projectSectionDivider({
            key: g.key,
            title: g.title,
            description: g.description,
            visibleWhen: g.visibleWhen,
            visibleWhenFault: g.visibleWhenFault,
            members: g.fields.map((f) => f.name),
            className: g.className,
            collapse,
          }),
        );
        // A collapsed group keeps its fields registered (values preserved) but
        // out of the DOM — only ever while its row carries the control.
        allFields.push(...(collapse.collapsed ? g.fields.map((f) => ({ ...f, hidden: true })) : g.fields));
      });

      const stackedFormSchema: FormSchema = { ...sharedFormSchema, fields: allFields };
      return <SchemaRenderer schema={stackedFormSchema} />;
    }

    // Derived field-group sections (object `fieldGroups` metadata) — rendered
    // as ONE form with virtual 'section-divider' headers (same pattern as
    // DrawerForm), so every group's fields share a single react-hook-form
    // instance and the footer submit collects them all.
    if (derivedSections?.length) {
      const columns = (Number(derivedSections[0]?.columns) || 1) as 1 | 2 | 3 | 4;
      const allFields: FormField[] = [];
      derivedSections.forEach((section, index) => {
        // FLS first, so a group whose every field is non-readable drops its
        // header along with its fields.
        const body = gateFields(buildSectionFields(section));
        if (!body.length) return;
        const title = section.name
          ? sectionLabel(schema.objectName, section.name, section.label || section.name)
          : section.label;
        const key = section.name || String(index);
        // The group's declared collapse state, which `deriveFieldGroupSections`
        // has always handed this route and this route used to drop
        // (objectui#9849 step two — director ruling letter E, item 1).
        const collapse = resolveSectionCollapse(section, {
          live: collapsedSections[key],
          title,
          description: section.description,
          where: `ModalForm field group '${key}' of object '${schema.objectName}'`,
          setCollapsed: (next) => setSectionCollapsed(key, next),
        });
        // The ONE path (objectui#9849). This push is the site the card was
        // filed on: it rebuilt the row key by key WITHOUT `description`, while
        // its stacked sibling carried it. Going through the shared projection
        // is what fixed it, and ⛔ not a key added back here.
        allFields.push(
          ...projectSectionDivider({
            key,
            title,
            description: section.description,
            visibleWhen: (section as any).visibleWhen,
            visibleWhenFault: section.visibleWhenFault,
            members: body.map((f) => f.name),
            collapse,
          }),
        );
        const laidOut = columns > 1 ? applyAutoColSpan(body, columns) : body;
        allFields.push(...(collapse.collapsed ? laidOut.map((f) => ({ ...f, hidden: true })) : laidOut));
      });
      const groupedContainerClass = CONTAINER_GRID_COLS[columns];
      const groupedFormSchema: FormSchema = {
        ...baseFormSchema,
        fields: allFields,
        columns,
        ...(groupedContainerClass ? { fieldContainerClass: groupedContainerClass } : {}),
      };
      return <SchemaRenderer schema={groupedFormSchema} />;
    }

    // Reuse pre-computed auto-layout result for flat fields
    const layoutResult = autoLayoutResult ?? applyAutoLayout(formFields, objectSchema, flatColumns, schema.mode);

    // Flat fields layout — use container-query grid classes so the form
    // responds to the modal width, not the viewport width.
    const containerFieldClass = CONTAINER_GRID_COLS[layoutResult.columns || 1];

    const flatFormSchema: FormSchema = {
      ...baseFormSchema,
      fields: gateFields(layoutResult.fields),
      columns: layoutResult.columns,
      ...(containerFieldClass ? { fieldContainerClass: containerFieldClass } : {}),
    };
    return <SchemaRenderer schema={flatFormSchema} />;
  };

  // Master-detail in a modal: when the schema declares inline child collections,
  // render the master-detail form inside the dialog (it owns its own Save/Cancel
  // action bar, so the modal footer is suppressed). Persisted atomically.
  const subforms = (schema as any).subforms as any[] | undefined;
  // objectui#11000 — why `gateFields` locked every field, when the lock is the
  // form-wide one: the affordance for the mode is closed. Drawn above the
  // fields once they are on screen; the master-detail body draws its own
  // through the `ObjectForm` it renders.
  const closedAffordanceNotice = !error && !loading ? (
    <ClosedAffordanceNotice
      affordance={closedFormAffordance({
        perms,
        objectName: schema.objectName,
        mode: schema.mode,
        objectSchema,
      })}
      objectName={schema.objectName}
      objectSchema={objectSchema}
    />
  ) : null;
  // Design/preview surfaces render this live on a canvas; a portalled modal Dialog
  // would lock the whole editor (Radix sets body pointer-events:none + a focus trap
  // while open). Render the form body inline instead — a hard backstop complementing
  // the schema-level coercion the preview surfaces apply. (The master-detail line
  // items are omitted in preview; the base field layout is what the canvas shows.)
  if (previewMode) {
    return (
      <div className="@container rounded-md border bg-card p-4">
        {(schema.title || schema.description) && (
          <div className="mb-3 space-y-0.5">
            {schema.title && <div className="text-sm font-semibold">{schema.title}</div>}
            {schema.description && <p className="text-xs text-muted-foreground">{schema.description}</p>}
          </div>
        )}
        {closedAffordanceNotice}
        {renderContent()}
      </div>
    );
  }

  if (subforms?.length && schema.mode !== 'view') {
    return (
      <Dialog open={isOpen} onOpenChange={schema.onOpenChange}>
        <MobileDialogContent
          showCloseButton={showCloseButton}
          onOpenAutoFocus={initialFieldFocus.onOpenAutoFocus}
          onCloseAutoFocus={initialFieldFocus.onCloseAutoFocus}
          className={cn(sizeClass, 'flex flex-col h-[100dvh] sm:h-auto sm:max-h-[90vh] overflow-hidden p-0', className, schema.className)}
        >
          {(schema.title || schema.description) && (
            <DialogHeader className="shrink-0 px-4 pt-4 sm:px-6 sm:pt-6 pb-2 border-b">
              {schema.title && <DialogTitle>{schema.title}</DialogTitle>}
              {schema.description ? (
                <DialogDescription>{schema.description}</DialogDescription>
              ) : (
                <DialogDescription className="sr-only">{t('form.masterDetail.editorDescription')}</DialogDescription>
              )}
            </DialogHeader>
          )}
          <div className="@container flex-1 overflow-y-auto px-4 sm:px-6 py-4">
            <Suspense fallback={<ModalFormBodyPending />}>
            <MasterDetailForm
              schema={{
                type: 'object-master-detail-form',
                objectName: schema.objectName,
                mode: schema.mode === 'edit' ? 'edit' : 'create',
                recordId: schema.recordId,
                fields: schema.fields as any,
                sections: schema.sections as any,
                // Forward create-mode prefills (e.g. a subtable child's parent
                // pre-link, objectstack-ai/objectstack#2604) — MasterDetailForm consumes them the same
                // way the flat form path does.
                initialValues: schema.initialValues,
                initialData: schema.initialData,
                submitText: submitLabel,
                cancelText: cancelLabel,
                details: subforms as any,
                onSuccess: async (rec: any) => { await schema.onSuccess?.(rec); schema.onOpenChange?.(false); },
                onError: schema.onError,
                onCancel: () => schema.onOpenChange?.(false),
              }}
              dataSource={dataSource}
            />
            </Suspense>
          </div>
        </MobileDialogContent>
      </Dialog>
    );
  }

  const hasFooter = !loading && !error && (showSubmit || showCancel);

  return (
    <Dialog
      open={isOpen}
      onOpenChange={(open) => {
        // Radix routes backdrop click, Escape, and the X button all through
        // here. Intercept closes so unsaved input isn't silently discarded.
        if (open) { schema.onOpenChange?.(true); return; }
        attemptClose(false);
      }}
    >
      <MobileDialogContent
        showCloseButton={showCloseButton}
        onOpenAutoFocus={initialFieldFocus.onOpenAutoFocus}
        onCloseAutoFocus={initialFieldFocus.onCloseAutoFocus}
        className={cn(sizeClass, 'flex flex-col h-[100dvh] sm:h-auto sm:max-h-[90vh] overflow-hidden p-0', className, schema.className)}
      >
        {(schema.title || schema.description) && (
          <DialogHeader className="shrink-0 px-4 pt-4 sm:px-6 sm:pt-6 pb-2 border-b">
            {schema.title && <DialogTitle>{schema.title}</DialogTitle>}
            {schema.description ? (
              <DialogDescription>{schema.description}</DialogDescription>
            ) : (
              <DialogDescription className="sr-only">
                {t('form.dialogDescriptionFallback')}
              </DialogDescription>
            )}
          </DialogHeader>
        )}

        <div className="@container flex-1 overflow-y-auto px-4 sm:px-6 py-4">
          {/* Every upload widget below reports into this scope, however deep —
              a section, a tab, a subform row (objectui#10166). */}
          <UploadGateProvider gate={uploadGate}>
            {closedAffordanceNotice}
            {/* The dialog owns its body's wait (objectui#12559) — see
                `ModalFormBodyPending`. */}
            <Suspense fallback={<ModalFormBodyPending />}>
              {renderContent()}
            </Suspense>
          </UploadGateProvider>
        </div>

        {/* Sticky footer — always visible action buttons */}
        {hasFooter && (
          <div className="shrink-0 border-t px-4 sm:px-6 py-3 bg-background" data-testid="modal-form-footer">
            {/* The REASON the Save below is disabled (objectui#10166). Above the
                row rather than inside it so it reads before the dead control,
                and so a long sentence never squeezes the buttons. */}
            <UploadInFlightNotice gate={uploadGate} />
            <div className="flex flex-col sm:flex-row gap-2 sm:justify-end">
              {showCancel && (
                <Button
                  type="button"
                  variant="outline"
                  onClick={handleCancel}
                  disabled={isSubmitting}
                  className="w-full sm:w-auto"
                >
                  {cancelLabel}
                </Button>
              )}
              {showSubmit && (
                <Button
                  type="submit"
                  form={formId}
                  disabled={isSubmitting || uploadGate.uploading}
                  className="w-full sm:w-auto"
                >
                  {isSubmitting && <Loader2 className="mr-2 h-4 w-4 animate-spin" />}
                  {uploadGate.uploading ? uploadGate.busyLabel : submitLabel}
                </Button>
              )}
            </div>
          </div>
        )}

        {/* Unsaved-changes guard — rendered INSIDE DialogContent so its portal
            inherits the Dialog's Radix layer context (focus scope + dismissable
            layer) through React. As a sibling of <Dialog> it had no such
            context, so the still-open modal swallowed its button clicks and
            "Keep editing" did nothing. Nesting lets Radix stack the two modals
            correctly: the alert becomes the topmost layer and its buttons work. */}
        <AlertDialog open={discardOpen} onOpenChange={setDiscardOpen}>
          <AlertDialogContent>
            <AlertDialogHeader>
              <AlertDialogTitle>{t('form.discardTitle')}</AlertDialogTitle>
              <AlertDialogDescription>
                {t('form.discardMessage')}
              </AlertDialogDescription>
            </AlertDialogHeader>
            <AlertDialogFooter>
              <AlertDialogCancel onClick={() => { cancelIntentRef.current = false; }}>
                {t('form.keepEditing')}
              </AlertDialogCancel>
              <AlertDialogAction onClick={finalizeClose}>
                {t('form.discard')}
              </AlertDialogAction>
            </AlertDialogFooter>
          </AlertDialogContent>
        </AlertDialog>
        {/* Same nesting rationale as the discard guard above: as a child of
            the Dialog content the conflict alert stacks as the topmost Radix
            layer, so its buttons receive clicks while the modal stays open. */}
        {conflictDialog}
      </MobileDialogContent>
    </Dialog>
  );
};

/**
 * What the dialog's body shows while a field widget's code loads
 * (objectui#12559).
 *
 * The field widgets `@object-ui/fields` registers are `React.lazy`: a type's
 * chunk is fetched the first time a form draws it, and that first render
 * SUSPENDS. With no boundary inside the dialog, the suspension left the dialog
 * and landed on the HOST's nearest `<Suspense>`. A record dialog is an overlay
 * a host mounts beside its pages — the console mounts this one beside its
 * routes, under the shell's root boundary — so expanding a collapsed section
 * whose fields used a type not loaded yet swapped the WHOLE console, dialog
 * included, for the root fallback while the chunk loaded. A full-page form
 * sits inside its route's boundary and hid only its page.
 *
 * So the dialog owns its body's wait, the shape `FlowRunner` gives its screen
 * body: the header and footer stay, the body shows this placeholder, and the
 * form underneath is hidden, not unmounted — React keeps its state, so the
 * section the user opened is open and every typed value is kept when the
 * widget lands. Distinct from `modal-form-skeleton`, which is the record READ's
 * loading state.
 *
 * A section toggle no longer reaches it (objectui#13246): the toggle is a
 * transition (`setSectionCollapsed`), which keeps the drawn body on screen
 * instead. Hiding the body hid the header the user had just pressed, and a
 * browser drops focus from an element it stops rendering. The boundary still
 * owns every wait an ordinary update starts, the body's first draw after the
 * load among them.
 */
function ModalFormBodyPending() {
  return (
    <div className="space-y-4" data-testid="modal-form-body-pending" aria-hidden="true">
      {[1, 2, 3].map((i) => (
        <div key={i} className="space-y-2">
          <Skeleton className="h-4 w-24" />
          <Skeleton className="h-10 w-full" />
        </div>
      ))}
    </div>
  );
}

export default ModalForm;
