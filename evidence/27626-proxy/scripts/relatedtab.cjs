// Does the warm drawer (whose related probes were prefetched with select=id during the previous open) render its Related tab correctly?
const { chromium } = require('playwright');
const fs = require('fs');
const SHOTS = '/tmp/claude-0/-home-claude-objectstack/7935dc52-4879-5e5d-a8db-0047aee0acbe/scratchpad/issue-27626/preview/shots/';
const BASE = 'http://localhost:38618';
const sleep = ms => new Promise(r => setTimeout(r, ms));
(async () => {
  const browser = await chromium.launch();
  const ctx = await browser.newContext({ viewport: { width: 1440, height: 900 } });
  const page = await ctx.newPage();
  const T0 = Date.now(); let phase = 'load';
  const log = { run: 'related tab, cold vs warm, crm_account', viewport: '1440x900', phases: [], requests: [], console: [] };
  page.on('request', q => { if (!['script', 'stylesheet', 'image', 'font'].includes(q.resourceType())) log.requests.push({ t: Date.now() - T0, phase, method: q.method(), url: q.url(), postData: q.postData() || undefined }); });
  page.on('console', m => { if (m.type() === 'error') log.console.push({ phase, text: m.text().slice(0, 300) }); });
  page.on('pageerror', e => log.console.push({ phase, pageerror: String(e).slice(0, 300) }));
  await page.request.post(BASE + '/api/v1/auth/sign-in/email', { data: { email: 'admin@objectos.ai', password: 'admin123' } });
  const mark = n => { phase = n; log.phases.push({ name: n, start: Date.now() - T0 }); };
  await page.goto(BASE + '/apps/com.example.crm/crm_account', { waitUntil: 'domcontentloaded', timeout: 180000 });
  await page.waitForSelector('a[data-testid="primary-field-link"]', { timeout: 180000 }); await sleep(10000);
  const dlg = page.locator('[role="dialog"]');
  mark('open-cold'); await page.locator('a[data-testid="primary-field-link"]').nth(0).click(); await sleep(8000);
  mark('cold-related-tab'); await dlg.getByRole('tab', { name: /Related/ }).click(); await sleep(6000);
  log.coldRelatedText = (await dlg.innerText()).slice(0, 2500);
  await page.screenshot({ path: SHOTS + '25-crm_account-cold-related-tab.png' });
  mark('close'); await page.keyboard.press('Escape'); await sleep(5000);
  mark('open-warm'); await page.locator('a[data-testid="primary-field-link"]').nth(1).click(); await sleep(8000);
  mark('warm-related-tab'); await dlg.getByRole('tab', { name: /Related/ }).click(); await sleep(6000);
  log.warmRelatedText = (await dlg.innerText()).slice(0, 2500);
  await page.screenshot({ path: SHOTS + '26-crm_account-warm-related-tab.png' });
  mark('warm-timeline-tab'); await dlg.getByRole('tab', { name: /Timeline/ }).click(); await sleep(6000);
  await page.screenshot({ path: SHOTS + '27-crm_account-warm-timeline-tab.png' });
  mark('close2'); await page.keyboard.press('Escape'); await sleep(4000);
  mark('done');
  fs.writeFileSync(SHOTS + '28-related-tab-requests.json', JSON.stringify(log, null, 2));
  for (const p of log.phases) { if (p.name === 'done') continue; const rs = log.requests.filter(r => r.phase === p.name); console.log(`\n== ${p.name}: ${rs.length}`); rs.forEach(r => console.log('  ', r.method, r.url.replace(BASE, '').slice(0, 170))); }
  console.log('\nCOLD RELATED TEXT:\n' + log.coldRelatedText.slice(0, 1200));
  console.log('\nWARM RELATED TEXT:\n' + log.warmRelatedText.slice(0, 1200));
  console.log('console', log.console);
  await browser.close();
})().catch(e => { console.error('ERR', e); process.exit(1); });
