/**
 * The platform's per-locale name of every standard unit code (ADR-0158 L2,
 * 2A: "Standard U1 codes get a platform-shipped per-locale label table"),
 * served by the i18n service in each platform bundle's `messages` group.
 *
 * - The English base is `STANDARD_UNIT_NAMES` in `@objectstack/spec`, read
 *   here and never re-typed, so the `en` bundle is a copy of the source.
 * - Each message key is single-segment (`standardUnitKGM`). Both i18n
 *   implementations resolve a dotted key by walking nested objects, so a flat
 *   `messages` key holding a dot would never resolve; the same rule as
 *   plugin-audit's `messages.ts`.
 * - A reader asks `messages.standardUnit<CODE>` and falls back to the spec's
 *   English name: the UI's quantity display (`useStandardUnitLabel` in
 *   `@object-ui/fields`), an export, an MCP tool.
 *
 * A pin test holds every locale below to exactly the codes of
 * `STANDARD_UNITS`.
 */

import { STANDARD_UNIT_NAMES } from '@objectstack/spec/data';

/** The `messages` key of a standard unit code's name. */
export function standardUnitMessageKey(code: string): string {
  return `standardUnit${code}`;
}

