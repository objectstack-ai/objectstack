/**
 * The `messages` entries of one platform bundle locale: the English base for
 * `en`, the translated names otherwise.
 */
export function standardUnitMessages(locale: string): Record<string, string> {
  const names = locale === 'en' ? STANDARD_UNIT_NAMES : STANDARD_UNIT_NAME_TRANSLATIONS[locale];
  if (!names) throw new Error(`No standard unit names for locale ${locale}`);
  return Object.fromEntries(Object.entries(names).map(([code, name]) => [standardUnitMessageKey(code), name]));
}
