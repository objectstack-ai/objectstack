/**
 * check-lockstep-package-count -- holds every PROSE restatement of "how many
 * packages sit in the lockstep Changesets `fixed` group" to the group itself.
 *
 *   node scripts/check-lockstep-package-count.mjs             # verify
 *   node scripts/check-lockstep-package-count.mjs --fix       # regenerate
 *   node scripts/check-lockstep-package-count.mjs --self-test # verify the checker itself
 *
 * ## The defect (#17039)
 *
 * `.changeset/config.json`'s `fixed` array is the one true count: Changesets
 * applies the highest bump found anywhere in the group to EVERY name in it, so
 * the array's length IS the number of packages one stray `major` would
 * promote. `check-changeset-fixed.mjs` already gates that array against the
 * real workspace on every release. Nothing gated the THREE places that repeat
 * its length back to a reader in prose:
 *
 *   - content/docs/protocol/backward-compatibility.mdx, twice ("...would
 *     promote all 69 published packages", "all **69** packages published
 *     from this repository...")
 *   - scripts/publish-smoke-pack.mjs's own header comment ("enumerates the
 *     same 69 names")
 *
 * All three were written when the group had 69 members and went silently
 * wrong the day a 70th package joined it -- nothing reds when `fixed[0]`
 * grows. This is the second confirmed instance of the class #16919 was filed
 * for (content/docs/permissions/system-context.mdx's hand-maintained counts,
 * generated by check-system-context-census.mjs): same discipline -- generate
 * the fact, verify the anchor still resolves, fail loud on drift -- but
 * deliberately NOT the same machinery. That script's job is an open-ended
 * CENSUS over the whole repo (call sites it has to go find); this job's
 * source of truth is a one-line read
 * (`require('.changeset/config.json').fixed[0].length`), and the population
 * of sentences that repeat it is small, closed and enumerated by hand once,
 * in OCCURRENCES below. Building a second census-shaped script for a
 * one-line fact would be the same fragility in a nicer coat.
 *
 * ## Why one script for three occurrences, not three patches
 *
 * All three sentences restate the SAME fact from the SAME source. Hand-fixing
 * the digit in each would leave three places to remember next time the group
 * grows -- exactly the failure this card exists to close. OCCURRENCES is the
 * one shared mechanism's only extension point: a fourth prose restatement
 * elsewhere gets a fourth row, not a fourth script.
 *
 * ## What "check" verifies, and the failure mode #17041 named
 *
 * A gate that recomputes the truth but can never disagree with what is on
 * disk is not a gate. So every occurrence's ANCHOR must resolve to EXACTLY
 * ONE match in its file before the number it captured is compared to the
 * truth: zero matches (the sentence was reworded) or more than one both
 * report ROTTED_ANCHOR rather than being silently skipped as agreement --
 * silence on a stale number is the bug this exists to fix, and silence on a
 * rotted anchor is the same bug one level up.
 *
 * `--fix` rewrites ONLY the digits inside a matched anchor -- never anything
 * else in the file -- and only for occurrences that disagree; an occurrence
 * already correct is left byte-identical, so `--fix` on an already-clean tree
 * is a no-op (checked by --self-test). The narrowness follows AGENTS.md's
 * `packages/spec` `--fix` precedent: regenerating what nobody proved stale
 * lets a real, unrelated edit hide inside a mechanical-looking diff.
 */

import { mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import * as os from 'node:os';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const repoRoot = resolve(__dirname, '..');

/** Reads the one true count: the length of the lockstep `fixed` group. */
function trueCount(root) {
  const configPath = resolve(root, '.changeset/config.json');
  const config = JSON.parse(readFileSync(configPath, 'utf8'));
  if (!Array.isArray(config.fixed) || !Array.isArray(config.fixed[0])) {
    throw new Error(`${configPath}: "fixed" is not an array containing a group array`);
  }
  return config.fixed[0].length;
}

// Every prose restatement of the lockstep package count, as of #17039. Each
// pattern brackets a run of digits with enough literal context on both sides
// to be unambiguous; the digits are the ONLY thing --fix ever rewrites.
const OCCURRENCES = [
  {
    file: 'content/docs/protocol/backward-compatibility.mdx',
    label: 'Breaking Change Process, step 4',
    pattern: /(would promote all )(\d+)( published packages\.)/,
  },
  {
    file: 'content/docs/protocol/backward-compatibility.mdx',
    label: '"Which surfaces this covers" section',
    pattern: /(all \*\*)(\d+)(\*\* packages published from this repository)/,
  },
  {
    file: 'scripts/publish-smoke-pack.mjs',
    label: 'header comment, "Source of truth" paragraph',
    pattern: /(enumerates the same )(\d+)( names)/,
  },
];

function globalOf(pattern) {
  return new RegExp(pattern.source, pattern.flags.includes('g') ? pattern.flags : `${pattern.flags}g`);
}

function readOccurrence(root, occurrence) {
  const path = resolve(root, occurrence.file);
  const text = readFileSync(path, 'utf8');
  const matches = [...text.matchAll(globalOf(occurrence.pattern))];
  if (matches.length !== 1) {
    return { path, text, rotted: true, matchCount: matches.length };
  }
  return { path, text, rotted: false, current: Number(matches[0][2]) };
}

/**
 * Checks (and optionally fixes) every occurrence against the true count.
 * Pure with respect to `fix`: false never touches disk; `fix: true` rewrites
 * only the occurrences it finds stale, byte-for-byte identical to the
 * original elsewhere in the file.
 */
function run(root, { fix = false } = {}) {
  const truth = trueCount(root);
  const results = [];

  for (const occurrence of OCCURRENCES) {
    const read = readOccurrence(root, occurrence);
    if (read.rotted) {
      results.push({ ...occurrence, status: 'ROTTED_ANCHOR', matchCount: read.matchCount });
      continue;
    }
    if (read.current === truth) {
      results.push({ ...occurrence, status: 'OK', current: read.current });
      continue;
    }
    results.push({ ...occurrence, status: 'STALE', current: read.current, truth });
    if (fix) {
      const next = read.text.replace(occurrence.pattern, `$1${truth}$3`);
      writeFileSync(read.path, next);
    }
  }

  const dirty = results.some((r) => r.status !== 'OK');
  return { truth, results, dirty };
}

function formatReport({ truth, results }) {
  const lines = [
    `lockstep package count (source: .changeset/config.json fixed[0].length) = ${truth}`,
  ];
  for (const r of results) {
    if (r.status === 'OK') {
      lines.push(`  OK      ${r.file} -- ${r.label} (reads ${r.current})`);
    } else if (r.status === 'STALE') {
      lines.push(`  STALE   ${r.file} -- ${r.label}: reads ${r.current}, truth is ${r.truth}`);
    } else {
      lines.push(
        `  ROTTED  ${r.file} -- ${r.label}: anchor matched ${r.matchCount} time(s), expected exactly 1`,
      );
    }
  }
  return lines.join('\n');
}

// ---------------------------------------------------------------------------
// --self-test: fixture-based, touches no real repo file. Builds a throwaway
// root with the same relative paths OCCURRENCES names, so the real anchors
// are exercised against synthetic content.
// ---------------------------------------------------------------------------

function selfTest() {
  const write = writeFileSync;

  const failures = [];
  const t = (name, ok) => {
    if (!ok) failures.push(name);
  };

  const tmp = mkdtempSync(join(os.tmpdir(), 'check-lockstep-package-count-'));
  try {
    mkdirSync(join(tmp, 'content/docs/protocol'), { recursive: true });
    mkdirSync(join(tmp, 'scripts'), { recursive: true });

    const configOf = (n) =>
      JSON.stringify({ fixed: [Array.from({ length: n }, (_, i) => `@objectstack/pkg-${i}`)] });

    const docOf = (n) =>
      [
        '4. **Release** -- ... because under lockstep one `major` would promote all ' +
          `${n} published packages.`,
        '',
        `**All of them.** ... all **${n}** packages published from this repository ...`,
      ].join('\n');

    const scriptCommentOf = (n) => ` * .changeset/config.json enumerates the same ${n} names, but ...`;

    const writeFixture = (n) => {
      write(join(tmp, '.changeset', 'config.json'), configOf(n));
    };
    mkdirSync(join(tmp, '.changeset'), { recursive: true });

    // Case 1: everything stale (69 written everywhere, truth is 70) -- check
    // must red and NAME both numbers, never silently pass.
    writeFixture(70);
    write(join(tmp, 'content/docs/protocol/backward-compatibility.mdx'), docOf(69));
    write(join(tmp, 'scripts/publish-smoke-pack.mjs'), scriptCommentOf(69));

    const before = run(tmp, { fix: false });
    t('stale fixture: truth read as 70', before.truth === 70);
    t('stale fixture: reports dirty', before.dirty === true);
    t(
      'stale fixture: every occurrence reported STALE with both numbers named',
      before.results.every((r) => r.status === 'STALE' && r.current === 69 && r.truth === 70),
    );
    t(
      'stale fixture: check-only (no fix) touched no file',
      readFileSync(join(tmp, 'content/docs/protocol/backward-compatibility.mdx'), 'utf8') ===
        docOf(69),
    );

    // Case 2: --fix converges, and a second run is idempotent (byte-identical).
    const fixed = run(tmp, { fix: true });
    t('fix run: no longer dirty after fix', fixed.dirty === false || run(tmp, { fix: false }).dirty === false);
    const afterFirstFix = {
      doc: readFileSync(join(tmp, 'content/docs/protocol/backward-compatibility.mdx'), 'utf8'),
      script: readFileSync(join(tmp, 'scripts/publish-smoke-pack.mjs'), 'utf8'),
    };
    t('fix run: doc now reads the true count', afterFirstFix.doc === docOf(70));
    t('fix run: script comment now reads the true count', afterFirstFix.script === scriptCommentOf(70));

    run(tmp, { fix: true }); // second fix pass
    const afterSecondFix = {
      doc: readFileSync(join(tmp, 'content/docs/protocol/backward-compatibility.mdx'), 'utf8'),
      script: readFileSync(join(tmp, 'scripts/publish-smoke-pack.mjs'), 'utf8'),
    };
    t('idempotence: doc byte-identical after a second --fix pass', afterSecondFix.doc === afterFirstFix.doc);
    t(
      'idempotence: script comment byte-identical after a second --fix pass',
      afterSecondFix.script === afterFirstFix.script,
    );

    // Case 3: a reworded sentence rots the anchor -- must report ROTTED, never OK.
    write(
      join(tmp, 'content/docs/protocol/backward-compatibility.mdx'),
      'This sentence no longer mentions any package count at all.',
    );
    const rotted = run(tmp, { fix: false });
    const rottedRows = rotted.results.filter(
      (r) => r.file === 'content/docs/protocol/backward-compatibility.mdx',
    );
    t('rotted anchor: reported as ROTTED_ANCHOR, not OK', rottedRows.every((r) => r.status === 'ROTTED_ANCHOR'));
    t('rotted anchor: reports dirty (never a silent pass)', rotted.dirty === true);

    // Case 4: a duplicated anchor (two matches) is ALSO rotted, not "pick the first".
    write(
      join(tmp, 'content/docs/protocol/backward-compatibility.mdx'),
      `${docOf(70)}\n${docOf(70)}`,
    );
    const duped = run(tmp, { fix: false });
    const dupedRows = duped.results.filter(
      (r) => r.file === 'content/docs/protocol/backward-compatibility.mdx',
    );
    t(
      'duplicated anchor: reported as ROTTED_ANCHOR with matchCount 2',
      dupedRows.every((r) => r.status === 'ROTTED_ANCHOR' && r.matchCount === 2),
    );
  } finally {
    rmSync(tmp, { recursive: true, force: true });
  }

  if (failures.length > 0) {
    console.error(`✗ check:lockstep-package-count --self-test -- ${failures.length} failure(s):`);
    for (const f of failures) console.error(`  - ${f}`);
    process.exit(1);
  }
  console.log(`✓ check:lockstep-package-count --self-test -- all cases passed.`);
}

function main() {
  const args = process.argv.slice(2);

  if (args.includes('--self-test')) {
    selfTest();
    return;
  }

  const fix = args.includes('--fix');
  const outcome = run(repoRoot, { fix });
  console.log(formatReport(outcome));

  if (fix) {
    const after = run(repoRoot, { fix: false });
    if (after.dirty) {
      console.error(
        `\n✗ check:lockstep-package-count --fix did not converge -- rerun and inspect ROTTED_ANCHOR rows by hand.`,
      );
      process.exit(1);
    }
    console.log(`\n✓ check:lockstep-package-count --fix -- all occurrences now read ${outcome.truth}.`);
    return;
  }

  if (outcome.dirty) {
    const staleCount = outcome.results.filter((r) => r.status !== 'OK').length;
    console.error(
      `\n✗ check:lockstep-package-count -- ${staleCount} occurrence(s) disagree with the true count (${outcome.truth}). Run \`node scripts/check-lockstep-package-count.mjs --fix\`.`,
    );
    process.exit(1);
  }
  console.log(`\n✓ check:lockstep-package-count -- all ${OCCURRENCES.length} occurrence(s) agree with the true count (${outcome.truth}).`);
}

main();
