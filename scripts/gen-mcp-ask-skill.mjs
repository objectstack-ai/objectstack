/**
 * gen-mcp-ask-skill -- render `packages/mcp/src/ask-skill.generated.ts` from the
 * published ask-data skill, `skills/objectstack-ask/SKILL.md`.
 *
 *   node scripts/gen-mcp-ask-skill.mjs           # write the module
 *   node scripts/gen-mcp-ask-skill.mjs --check   # exit 1 when the module is stale, write nothing
 *
 * ## Why a generated module, and not a read of the skill at run time
 *
 * `GET /mcp/skill` serves the ask-data procedure (the data loop) to every MCP
 * client of an open server, and the published skill is its one source. Neither
 * of the two cheaper routes survives publishing:
 *
 * - `@objectstack/mcp` ships `dist`, README and CHANGELOG only, so a read of
 *   `skills/**` from disk answers nothing in an installed package; and
 *   `@objectstack/skills` exports only its `package.json`, so a runtime
 *   dependency on it would mean a filesystem read of another package's build
 *   output on every host, edge runtimes included.
 * - An import the bundler inlines (`skills/...SKILL.md` through an esbuild text
 *   loader) builds from a path outside the package, and turbo hashes a
 *   package's build from its own directory (`turbo.json`, `build.inputs`): a
 *   change to the skill alone would replay a cached `dist` with the old text.
 *
 * A module committed under the package's own `src/` is hashed with it, ships in
 * its `dist`, and is held equal to the skill by
 * `packages/mcp/src/skill-single-source-34686.test.ts`, which reads the skill
 * and fails when the two differ. Its failure text names this script.
 *
 * ## What is copied
 *
 * The skill's body after its title: every line after the first line that
 * starts with `# ` (the one H1), with leading and trailing blank lines
 * dropped. The frontmatter and the title stay with the skill: the served page
 * has its own frontmatter, and gives the text its own heading. The pin test
 * applies the same rule to the file it reads, so the rule is stated in two
 * places that must agree, and the pin goes red when they do not.
 */

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
const REPO = resolve(HERE, '..');
const SKILL = resolve(REPO, 'skills/objectstack-ask/SKILL.md');
const MODULE = resolve(REPO, 'packages/mcp/src/ask-skill.generated.ts');
const SKILL_REL = 'skills/objectstack-ask/SKILL.md';
const SELF_REL = 'scripts/gen-mcp-ask-skill.mjs';

function fail(message) {
  process.stderr.write(`gen-mcp-ask-skill: ${message}\n`);
  process.exit(2);
}

/** The skill's body after its one H1 title line, blank lines at either end dropped. */
function dataLoopText(markdown) {
  const lines = markdown.replace(/\r\n/g, '\n').split('\n');
  const title = lines.findIndex((line) => line.startsWith('# '));
  if (title === -1) fail(`${SKILL_REL} has no title line (a line starting with "# "); nothing to copy.`);
  return lines.slice(title + 1).join('\n').replace(/^\n+/, '').replace(/\n+$/, '');
}

/** One line as a single-quoted TypeScript string literal. */
function literal(line) {
  // A control character would be invisible in the module and in review: refuse it.
  if (/[\u0000-\u001f\u007f]/.test(line)) fail(`${SKILL_REL} carries a control character; refusing to copy it.`);
  return `'${line.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;
}

function renderModule(text) {
  const body = text.split('\n').map((line) => `  ${literal(line)},`).join('\n');
  return `// Copyright (c) 2026 ObjectStack. Licensed under the Apache-2.0 license.

// GENERATED by ${SELF_REL} from ${SKILL_REL}.
// Do not edit this file: change the skill, then run \`node ${SELF_REL}\`.

/**
 * The ask-data skill's data loop: its body after the title, served under its
 * own heading by \`renderSkillMarkdown\` (\`skill-md.ts\`) where the dataset tools
 * register for the grant. One source: the published skill.
 */
export const ASK_SKILL_DATA_LOOP: string = [
${body}
].join('\\n');
`;
}

const args = process.argv.slice(2);
const unknown = args.filter((a) => a !== '--check');
if (unknown.length > 0) fail(`unknown argument(s): ${unknown.join(' ')} (usage: node ${SELF_REL} [--check])`);

const expected = renderModule(dataLoopText(readFileSync(SKILL, 'utf8')));
let current;
try {
  current = readFileSync(MODULE, 'utf8');
} catch {
  current = undefined;
}

if (args.includes('--check')) {
  if (current === expected) {
    process.stdout.write(`gen-mcp-ask-skill: packages/mcp/src/ask-skill.generated.ts is current with ${SKILL_REL}.\n`);
    process.exit(0);
  }
  process.stderr.write(
    `gen-mcp-ask-skill: packages/mcp/src/ask-skill.generated.ts is ${current === undefined ? 'missing' : 'stale'} `
      + `against ${SKILL_REL}. Run: node ${SELF_REL}\n`,
  );
  process.exit(1);
}

if (current === expected) {
  process.stdout.write('gen-mcp-ask-skill: unchanged.\n');
} else {
  writeFileSync(MODULE, expected);
  process.stdout.write(`gen-mcp-ask-skill: wrote packages/mcp/src/ask-skill.generated.ts from ${SKILL_REL}.\n`);
}
