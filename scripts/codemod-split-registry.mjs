// ── Proof 2: the module's exports are unchanged ──────────────────────────────

/**
 * The names `registry.ts` exports, value and type alike, each with whether it
 * carries a value, as the TypeScript checker resolves them: a name the leaf
 * now declares and `registry.ts` re-exports by name counts as the same export.
 * The files are compiled in one in-memory project (no lib, no `node_modules`),
 * so a package import resolves to nothing and only the module graph under
 * `SRC_REL` is read.
 * @param {Map<string, string>} files  basename -> text, `registry.ts` among them
 * @returns {Map<string, 'value' | 'type'>}
 */
function exportedNames(tm, files) {
  const project = new tm.Project({
    useInMemoryFileSystem: true,
    compilerOptions: {
      target: tm.ts.ScriptTarget.ES2020, module: tm.ts.ModuleKind.ES2020,
      moduleResolution: tm.ts.ModuleResolutionKind.Node10, strict: true, noLib: true, allowJs: false,
    },
  });
  const fs = project.getFileSystem();
  for (const [file, text] of files) fs.writeFileSync(join(SRC_DIR, file), text);
  for (const [file] of files) project.addSourceFileAtPath(join(SRC_DIR, file));
  const sf = project.getSourceFileOrThrow(HOST_PATH);
  const checker = project.getTypeChecker().compilerObject;
  const moduleSymbol = checker.getSymbolAtLocation(sf.compilerNode);
  const out = new Map();
  if (!moduleSymbol) return out;
  for (const sym of checker.getExportsOfModule(moduleSymbol)) {
    const target = sym.flags & tm.ts.SymbolFlags.Alias ? checker.getAliasedSymbol(sym) : sym;
    // A package import resolves to nothing here (no `node_modules`): the
    // checker's unknown symbol, kind `unresolved` on both sides alike.
    // A name exported `type`-only carries no value whatever it aliases.
    const typeOnly = (sym.declarations ?? []).some((d) =>
      tm.ts.isExportSpecifier(d) && (d.isTypeOnly || d.parent.parent.isTypeOnly));
    const kind = typeOnly ? 'type'
      : target.flags & tm.ts.SymbolFlags.Value ? 'value' : target.flags & tm.ts.SymbolFlags.Type ? 'type' : 'unresolved';
    out.set(sym.getName(), kind);
  }
  return out;
}

/** The names the head's generated lever-(a) statement exports for the section modules (`Exported for the section modules`). */
function leverExportsOf(tm, headText) {
  const names = new Set();
  for (const st of parse(tm, HOST_PATH, headText).getStatements()) {
    if (!tm.Node.isExportDeclaration(st) || st.getModuleSpecifier() || !st.getFullText().includes(`${MARK} Exported for the section modules`)) continue;
    for (const spec of st.getNamedExports()) names.add(spec.getNameNode().getText());
  }
  return names;
}

/**
 * Every module under `SRC_DIR` that re-exports `registry.ts` with `export *`:
 * through one, a name `registry.ts` newly exports would reach the package. The
 * package entries (`index.ts`, `core.ts`) name what they take from it today.
 */
function starReexportersOnDisk() {
  const out = [];
  const walk = (dir) => {
    for (const entry of readdirSync(dir, { withFileTypes: true })) {
      const p = join(dir, entry.name);
      if (entry.isDirectory()) { if (entry.name !== 'node_modules' && entry.name !== 'dist') walk(p); continue; }
      if (!/\.ts$/.test(entry.name) || /\.(test|spec)\.ts$/.test(entry.name)) continue;
      for (const m of readFileSync(p, 'utf8').matchAll(/^\s*export\s+\*\s+(?:as\s+\w+\s+)?from\s+'(\.{1,2}\/[^']+)'/gm)) {
        if (resolve(dirname(p), m[1].replace(/\.js$/, '.ts')) === HOST_PATH) out.push(relative(SRC_DIR, p));
      }
    }
  };
  walk(SRC_DIR);
  return out;
}

/**
 * Exports-equality (Proof 2): the split `registry.ts` (with every generated
 * module) exports every name the base exports, each a value or a type as it
 * was; the only names it adds are the staying declarations lever (a) exports
 * for the section modules, and no module re-exports `registry.ts` with
 * `export *`, so none of those reaches the package. Returns the failures;
 * none = proved.
 */
function verifyExports(tm, baseText, headText, moduleTexts, { starReexporters = [] } = {}) {
  const before = exportedNames(tm, new Map([[HOST_BASENAME, baseText]]));
  const after = exportedNames(tm, new Map([[HOST_BASENAME, headText], ...moduleTexts]));
  // The generated additions: lever (a)'s names, and the statics route's
  // forwarder type and object when a moved body reads a non-public static.
  const lever = new Set([...leverExportsOf(tm, headText), ...(headText.includes(`// ${MARK} The statics of`) ? [STATICS_NAME, STATICS_HOST_NAME] : [])]);
  const failures = [];
  if (before.size === 0) failures.push(`the base ${HOST_BASENAME} exports nothing the checker can read: an equality over nothing is not a proof`);
  for (const [name, kind] of before) {
    if (!after.has(name)) failures.push(`exports: ${name} (${kind}) is exported at base and not by the split ${HOST_BASENAME}`);
    else if (after.get(name) !== kind) failures.push(`exports: ${name} is a ${kind} at base and a ${after.get(name)} after the split`);
  }
  const added = [...after.keys()].filter((name) => !before.has(name));
  for (const name of added) {
    if (!lever.has(name)) failures.push(`exports: ${name} (${after.get(name)}) is exported by the split ${HOST_BASENAME} and not at base, and is not a generated export (lever (a) or the statics route)`);
  }
  for (const file of starReexporters) {
    failures.push(`exports: ${file} re-exports ${HOST_BASENAME} with \`export *\`, so its generated names would reach the package; name what it takes instead`);
  }
  return { failures, count: before.size, values: [...before.values()].filter((k) => k === 'value').length, added };
}

function printExports(e) {
  for (const f of e.failures) console.error(`  ✗ ${f}`);
  console.log(`exports-equality: ${e.failures.length === 0 ? 'equal' : 'NOT equal'} — ${HOST_BASENAME} exports ${e.count} name(s) at base ` +
    `(${e.values} value(s), ${e.count - e.values} type(s)); the split exports ${e.failures.length === 0 ? 'every one, each the same kind' : 'a different set'}, ` +
    `plus ${e.added.length} generated name(s) (lever (a), the statics route) (${e.added.join(', ') || 'none'}), which no module re-exports with \`export *\``);
}

