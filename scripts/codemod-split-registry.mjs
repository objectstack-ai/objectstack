/**
 * codemod-split-registry — move whole sections of `SchemaRegistry`'s method
 * bodies out of `packages/objectql/src/registry.ts` into section modules, move
 * the top-level declarations ahead of the class into one leaf module,
 * deterministically, and prove the move: byte-identity, and the module's
 * exports unchanged.
 *
 *   node scripts/codemod-split-registry.mjs                 # plan: print the section table, prove it, write nothing
 *   node scripts/codemod-split-registry.mjs --write         # apply the split, then verify it
 *   node scripts/codemod-split-registry.mjs --verify --base <ref>
 *                                                           # re-prove a split on disk against registry.ts at <ref>
 *   node scripts/codemod-split-registry.mjs --self-test
 *   node scripts/codemod-split-registry.mjs --help
 *
 * ## Why a script, and whose
 *
 * The hot-file programme splits the platform's largest files one at a time
 * (ruling 6897467376 on #33949, item 1: `registry.ts` first). Each split is
 * generated by script against fresh `main` right before it is queued, the
 * original file stays as the forwarding entry so the public exports are
 * unchanged, and a split waits for every open PR touching its file to merge.
 * So the split is a COMMAND, not a diff: re-run on the latest `main`, never
 * rebased, never hand-edited.
 *
 * This script is the FIRST PASS of `scripts/codemod-split-engine.mjs`
 * (#29986, the objectql `engine.ts` split; the programme's pilot is
 * `scripts/codemod-split-sql-driver.mjs` and its other precedent
 * `scripts/codemod-split-protocol.mjs`), copied with its five later passes
 * left out and its host parameterised: the file `registry.ts`, the class
 * `SchemaRegistry`, the module prefix `registry-`, the card `#33949`. The cut
 * pattern, the stay rules, the leaf, the facet hosts, the byte-identity
 * proof and that pass's six self-test batteries are copied as they stand;
 * the copy renamed `engine.ts` / `ObjectQL` / "the engine" to `registry.ts` /
 * `SchemaRegistry` / "the registry" throughout, comments included, so a card
 * number in a comment below (#30020, #30051, …) is the engine card that
 * introduced the rule, not a registry one. Copied, never imported (the
 * engine script's constants are module-level), so a later fix to one is a
 * decision about the other too.
 *
 * In short, as that pass does it:
 *
 *  - A method stays on the class with its docblock, modifiers and signature
 *    byte-for-byte, so the published `.d.ts` keeps its names and an instance
 *    spy or a subclass override is still the one callers reach. Its body
 *    moves, unedited, into a static method of a stateless facet class in
 *    `registry-<section>.ts`, whose `this` is the facet's host: the
 *    `SchemaRegistry` members the body reads, typed AS the class members.
 *  - The stub is one line, `Facet.x.call(xHost.of(this), …)`; the host is ONE
 *    object per facet and registry (`HOSTS_MODULE`), built on first use by a
 *    factory the class's static block installs.
 *  - The top-level declarations ahead of the class (`const` / `function` /
 *    `interface` / `type`) move whole, with their comments, into
 *    `LEAF_MODULE`, which never imports `registry.ts` or a `registry-*`
 *    module; `registry.ts` re-exports each exported one by name.
 *  - A method or declaration a mechanical rule keeps (`STAY_REASONS`,
 *    `TOP_STAY_REASONS`) stays whole; the plan prints every one and why.
 *
 * ## What this script adds: exports-equality (Proof 2)
 *
 * The ruling's "public exports are unchanged" is checked, not assumed:
 * `verifyExports` compiles the base `registry.ts` alone and the split one
 * with every generated module in one in-memory TypeScript project and
 * requires the two export tables to be equal, name for name, each a value or
 * a type as it was. `--write` and `--verify` both run it; a difference is
 * exit 1 and nothing is written.
 *
 * ## Re-running it (the ruling's "regenerated against fresh main")
 *
 * On a branch freshly cut from the latest `origin/main`, ONE command:
 *
 *   node scripts/codemod-split-registry.mjs --write
 *
 * then the facade's `ceilings` row in `scripts/facade-delegation-registry.json`
 * is re-measured on the written file. `--verify --base origin/main` re-proves
 * the result on disk.
 *
 * ts-morph is a root devDependency, resolved from the root manifest.
 *
 * Exit codes: 0 done · 1 a proof failed (stop: the generated split is never
 * hand-edited to pass) · 2 the script could not run (unknown anchor, missing
 * prerequisite, bad arguments) · 3 an input does not parse (`ts-parse.mjs`'s
 * refusal, which names the parse errors).
 */

